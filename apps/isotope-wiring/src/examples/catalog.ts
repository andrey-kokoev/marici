export const CatalogEntrySchema = z
  .strictObject({
    name: z.string(),
    element: z.string(),
    protons: z.int().positive(),
    neutrons: z.int().nonnegative(),
    mass: z.int().positive(),
    hasDiagram: z.boolean(),
  })
  .readonly();
export const isotopeCatalog = z
  .array(CatalogEntrySchema)
  .readonly()
  .parse(
    rows.map(([name, protons, neutrons]) => ({
      name,
      protons,
      neutrons,
      mass: protons + neutrons,
      element: name.replace(/-\d+$/, ""),
      hasDiagram: hasDiagram(name),
    })),
  );
