import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import http from 'node:http'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium, expect } from '@playwright/test'
import { loadPublicResearchCoverage } from './public-research-coverage-config.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const dist = path.join(root, 'website/.vitepress/dist')
const { contract } = await loadPublicResearchCoverage(root)
const historicalProvenance = JSON.parse(await fs.readFile(path.join(root, 'config/current-research-provenance.v1.json'), 'utf8'))
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' }
const server = http.createServer(async (req, res) => {
  try {
    let file = path.resolve(dist, '.' + decodeURIComponent(new URL(req.url, 'http://local').pathname))
    if (!file.startsWith(dist + path.sep)) throw Error('Outside publication root')
    const stat = await fs.stat(file).catch(() => null)
    if (stat?.isDirectory()) file = path.join(file, 'index.html')
    else if (!stat && !path.extname(file)) file += '.html'
    res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream')
    res.end(await fs.readFile(file))
  } catch { res.writeHead(404); res.end('Not found') }
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${server.address().port}`
let browser
try {
  browser = await chromium.launch()
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport })
    const errors = [], failed = [], external = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (response.status() >= 400) failed.push(response.url()) })
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      if (['http:', 'https:'].includes(url.protocol) && url.origin !== base) { external.push(url.href); return route.abort() }
      return route.continue()
    })
    await page.goto(base + '/research/results/#next-discriminating-tests')
    await page.getByRole('link', { name: 'versioned current-frontier map', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Current frontier: missing source objects and acceptance tests' })).toBeVisible()
    await expect(page.locator('main tbody tr')).toHaveCount(contract.frontier.length)
    await expect(page.locator('main')).toContainText('14 passing checks')
    await expect(page.locator('main')).not.toContainText('three unresolved TODO requirements')
    const current = await page.request.get(base + '/research/frontier/current.json')
    assert.equal((await current.json()).current.snapshot_id, contract.snapshot_id)
    const old = await page.request.get(base + '/research/frontier/public-research-frontier-v1.json')
    assert.equal((await old.json()).snapshot_id, 'public-research-frontier-v1')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Frontier overflows the viewport')
    await expect(page.locator('main')).toContainText('Stop this local objective')
    await page.getByRole('link', { name: 'common-witness assembly', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^WG common-witness source-certified coherent assembly/ })).toBeVisible()
    for (const boundary of ['literal input object', 'Do not reopen this local objective', 'not rerun for publication', 'not pinned by the historical ten-family v1 snapshot']) await expect(page.locator('main')).toContainText(boundary)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'WG result overflows the viewport')
    await page.goto(base + '/research/frontier/current')
    await page.getByRole('link', { name: 'retained four-facet/higher comparisons and candidate assembly coherence', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^Ramsey retained correspondence and declared-candidate assembly coherence/ })).toBeVisible()
    for (const boundary of ['local revision 32', 'graph admission remains revision 19', 'not a new Agda/Rzk/Lean kernel certificate', 'joint44-native-source-selection', 'negative-direction-policy-native-descent', 'not rerun for publication']) await expect(page.locator('main')).toContainText(boundary)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Ramsey result overflows the viewport')
    await page.goto(base + '/research/results/')
    await page.getByRole('link', { name: 'dated Ramsey mathematical-programme guide', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^Ramsey mathematical programme: selected November notes/ })).toBeVisible()
    for (const boundary of ['not independently verified', 'no general Ramsey formula', 'unrestricted n = 4 remains open', 'exactly 22 vertices', 'simultaneous-stability step remains missing', 'not found in the reviewed tree']) await expect(page.locator('main')).toContainText(boundary)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mathematical programme guide overflows the viewport')
    await page.goto(base + '/experiments/')
    await page.getByRole('link', { name: 'Which editor is hosted? Typed-app and Morse status', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^Which isotope editor is hosted/ })).toBeVisible()
    for (const boundary of ['development-only', 'not the hosted iframe editor', 'not a computed smooth atlas', 'not a gradient flow', 'not experimental validation']) await expect(page.locator('main')).toContainText(boundary)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Typed-app status guide overflows the viewport')
    await page.getByRole('link', { name: 'Hosted isotope wiring editor', exact: true }).click()
    const hosted = page.frameLocator('iframe.isotope-wiring')
    await expect(hosted.locator('#core-state')).toHaveText('Passed')
    assert.equal(await page.locator('iframe.isotope-wiring').getAttribute('srcdoc'), await fs.readFile(path.join(root, 'examples/isotope-wiring/index.html'), 'utf8'), 'Hosted editor was silently replaced')
    await expect(hosted.getByRole('button', { name: 'Morse', exact: true })).toHaveCount(0)
    await page.getByRole('link', { name: 'Validation and export limits', exact: true }).click()
    await page.getByRole('link', { name: 'Which editor is hosted? Typed-app and Morse status', exact: true }).click()
    await expect(page.locator('main')).toContainText('No public application route is selected')
    await page.goto(base + '/experiments/')
    await page.getByRole('link', { name: 'P/E revision-73 frontier and publication status', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^Persistent-seam P\/E: research frontier and publication status/ })).toBeVisible()
    for (const boundary of ['five-net public selection', 'not bundled', 'revision 73', 'f736-boundary-witness-record-graph-lift', 'unresolved source wording', 'not rerun']) await expect(page.locator('main')).toContainText(boundary)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'P/E publication-status guide overflows the viewport')
    const publicNets = await (await page.request.get(base + '/experiments/conjecture-nets.json')).json()
    assert.equal(publicNets.nets.length, 5)
    assert(!publicNets.nets.some(net => net.source === 'research/strominger/contracts/persistent-seam-pe-conjecture-net.v1.json'))
    await page.getByRole('link', { name: 'Open the five-net public explorer', exact: true }).click()
    await expect(page.locator('#graph .graph-node').first()).toBeVisible()
    await expect(page.locator('#net-select option')).toHaveCount(5)
    assert.deepEqual(await page.locator('#net-select option').evaluateAll(options => options.map(option => option.value)), contract.required_net_ids)
    await page.goto(base + '/research/frontier/current')
    await page.getByRole('link', { name: 'publication provenance guide', exact: true }).click()
    const download = page.getByRole('link', { name: 'Download the compact v1 provenance manifest', exact: true })
    await expect(download).toBeVisible()
    const response = await page.request.get(base + await download.getAttribute('href'))
    assert.equal(response.status(), 200)
    const metadata = await response.json()
    assert.deepEqual(metadata, historicalProvenance, 'Historical v1 must remain unchanged when selected coverage advances')
    assert.equal(metadata.scientific_replay_performed, false)
    assert((await response.body()).length < 65536)
    const successorDownload = page.getByRole('link', { name: 'Download the compact v2 successor manifest', exact: true })
    const successorResponse = await page.request.get(base + await successorDownload.getAttribute('href'))
    assert.equal(successorResponse.status(), 200)
    const successor = await successorResponse.json()
    assert.equal(successor.entries.length, 5)
    assert.equal(successor.entries.filter(entry => entry.kind === 'result').length, 2)
    assert.deepEqual([...new Set([...metadata.entries.map(entry => entry.slug), ...successor.entries.filter(entry => entry.kind === 'result').map(entry => entry.id)])].sort(), [...contract.required_result_slugs].sort(), 'Current required results must match the union of selected provenance families')
    assert.equal(successor.scientific_replay_performed, false)
    assert.equal(successor.receipt_source_compatibility, 'not revalidated')
    assert.equal(successor.predecessor.snapshot_id, metadata.snapshot_id)
    assert(successor.entries.find(entry => entry.id === 'ramsey-november-programme').unavailable_inputs.length >= 3)
    assert(successor.entries.find(entry => entry.id === 'held-pe-publication-explanation').compatibility_limits.join(' ').includes('registration mismatch'))
    assert((await successorResponse.body()).length < 65536)
    await page.goto(base + '/research/frontier/current')
    await page.getByRole('link', { name: contract.frontier[0].label, exact: true }).click()
    await expect(page.getByText('Metadata validation is not scientific replay.', { exact: false })).toBeVisible()
    assert.deepEqual(errors, [])
    assert.deepEqual(failed, [])
    assert.deepEqual(external, [])
    await page.close()
    console.log(`PASS frontier navigation, ${contract.frontier.length} acceptance rows, scoped WG completion and Ramsey verification levels, dated programme, typed-app and held P/E status, unchanged hosted editor and five-net selection, v1/v2 provenance downloads and result binding at ${viewport.width}px`)
  }
} finally {
  if (browser) await browser.close()
  await new Promise(resolve => server.close(resolve))
}
