import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

// Publish a byte-preserving copy; do not regenerate scientific reference values.
export async function prepareIsotopeReference(root, { check = false } = {}) {
  const source = 'research/kitaev/isotope-electron-shells.html'
  const target = 'website/public/experiments/isotope-electron-shells.html'
  const bytes = await fs.readFile(path.join(root, source))
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const marker = Buffer.from(`<!-- Generated by scripts/prepare-isotope-reference.mjs; edit ${source}.\nSource SHA-256: ${sha256}\nPublication copies the repository reference; it does not refresh or independently validate upstream data.\n-->\n`)
  const expected = Buffer.concat([marker, bytes])
  const output = path.join(root, target)
  if (check) {
    const actual = await fs.readFile(output).catch(error => {
      if (error.code === 'ENOENT') return null
      throw error
    })
    if (!actual?.equals(expected)) throw new Error('Stale isotope reference copy; run node scripts/prepare-isotope-reference.mjs')
  } else {
    await fs.mkdir(path.dirname(output), { recursive: true })
    await fs.writeFile(output, expected)
  }
  return { source, target, sha256, check }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  console.log(JSON.stringify(await prepareIsotopeReference(root, { check: process.argv.includes('--check') })))
}
