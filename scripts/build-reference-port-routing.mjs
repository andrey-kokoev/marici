import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createPortRouter } from '../public/experiments/reference-port-router.mjs';

const root=new URL('../',import.meta.url);
const read=path=>readFileSync(new URL(path,root),'utf8');
export function buildReferencePortRouting() {
  const source=read('research/chatgpt/reflection_port_routing.html');
  const data=JSON.parse(source.match(/<script id="data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
  createPortRouter(data); // Refuse to publish an inconsistent dataset.
  const digest=createHash('sha256').update(source).digest('hex');
  let html=source;
  function replace(oldText,newText) {
    if(html.split(oldText).length!==2) throw new Error(`Source anchor changed: ${oldText}`);
    html=html.replace(oldText,newText);
  }
  replace('<title>Reflection assembly: ports and routed comparisons</title>',
    '<title>Reference A · port routing</title>');
  replace('<h1>Exact seam ports · 32 routed history comparisons</h1>',
    '<p><a href="./hex-edge-grid.html" target="_top">← Hex-grid Process 1</a></p><h1>Reference A · seam ports and payload routing</h1>');
  replace('<div id="state"></div>',`<div id="state"></div>
<div class="box"><h2>Request payload</h2><p class="muted">Editable opaque values, retained by inherited label throughout the route. Each request keeps its own payload.</p><div id="packet-inputs"></div><pre id="packet-summary" aria-live="polite"></pre></div>`);
  replace('<th>Slot</th><th>Current four coordinates</th>',
    '<th>Slot</th><th>Payload</th><th>Transported coordinates</th>');
  replace('<div class="box warn" id="scope"></div>',
    '<div class="box warn" id="scope"></div><p id="packet-audit" class="muted"></p><details><summary>Retained packet record</summary><pre id="packet-record"></pre></details>');
  replace('</style>',`\n#packet-inputs{display:grid;gap:8px}#packet-inputs label{display:grid;grid-template-columns:24px minmax(0,1fr)}#packet-inputs input{min-width:0;width:100%;box-sizing:border-box;background:#111b25;color:var(--ink);border:1px solid #62788d;padding:6px;font:inherit}td{overflow-wrap:anywhere}table{table-layout:fixed}a{color:#acd3ed}\n</style>`);
  const model=read('public/experiments/reference-port-router.mjs').replace(/^export /gm,'');
  const ui=read('public/experiments/reference-port-routing-ui.js');
  replace('</body></html>',`<script>\n${model}\n${ui}\n</script></body></html>`);
  return `<!-- Generated by scripts/build-reference-port-routing.mjs; do not edit directly.\nSource: research/chatgpt/reflection_port_routing.html\nSource SHA-256: ${digest}\n-->\n${html}`;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const html=buildReferencePortRouting();
  writeFileSync(new URL('public/experiments/reflection-port-routing.html',root),html);
  console.log('Built public/experiments/reflection-port-routing.html');
}
