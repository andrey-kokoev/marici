import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const target = 'website/research/frontier/current.md'
const cell = value => value.replaceAll('|', '\\|').replace(/\r?\n/g, ' ')

export function renderPublicResearchFrontier(contract) {
  if (contract.schema !== 'marici.public-research-coverage.v1' || contract.scientific_dispositions_modified !== false || !contract.frontier?.length || !contract.as_of) throw Error('Invalid frontier coverage contract')
  const ids = new Set()
  const rows = contract.frontier.map(entry => {
    if (!/^[a-z0-9-]+$/.test(entry.id) || ids.has(entry.id) || !entry.link?.startsWith('/') || !entry.label || !entry.first_missing || !entry.acceptance) throw Error('Incomplete or duplicate frontier obligation')
    ids.add(entry.id)
    return `| [${cell(entry.label)}](${entry.link}) | ${cell(entry.first_missing)} | ${cell(entry.acceptance)} |`
  })
  return `<!-- Generated by scripts/prepare-public-research-frontier.mjs. Edit config/public-research-coverage.v1.json instead. -->\n\n# Current frontier: missing source objects and acceptance tests\n\n**As of:** ${contract.as_of}. Snapshot \`${contract.snapshot_id}\`.\n\n${contract.scope}. A listed blocker is not a new task claim or permission to mutate another source. This map does not rerun suppliers, apply graph transitions or convert publication closure into scientific completion.\n\n## Source-bound acceptance map\n\n| Research scope | First missing source object or map | Acceptance / reopening condition |\n|---|---|---|\n${rows.join('\n')}\n\n## How to use this map\n\nRead each condition at its linked source/result scope. Stop at the first absent authoritative object rather than inventing a downstream filler or silently substituting a different problem. Reopen a blocked scientific branch only when its named input or a distinct evidence-bearing test exists; this page is not a queue of waiting research leaves.\n\nThe [publication provenance guide](/research/provenance/current-results) identifies selected historical evidence and its compatibility limits. The [results index](/research/results/) separates reported positive checks, exclusions and unresolved physical identifications.\n\n## Publication consistency, not scientific proof\n\nThe coverage checker verifies required result/pages, canonical/generated freshness, actual navigation fragments and advertised curated-net IDs. These are website consistency tests. They do not prove acceptance conditions, certify a source theorem or supply empirical apparatus.\n`
}

export async function preparePublicResearchFrontier(base = root, { check = false } = {}) {
  const contract = JSON.parse(await fs.readFile(path.join(base, 'config/public-research-coverage.v1.json'), 'utf8'))
  const content = renderPublicResearchFrontier(contract)
  const output = path.join(base, target)
  if (check) {
    if (await fs.readFile(output, 'utf8').catch(() => null) !== content) throw Error('Stale generated research frontier')
  } else {
    await fs.mkdir(path.dirname(output), { recursive: true })
    await fs.writeFile(output, content)
  }
  return { snapshot_id: contract.snapshot_id, obligations: contract.frontier.length, target }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await preparePublicResearchFrontier(root, { check: process.argv.includes('--check') })))
}
