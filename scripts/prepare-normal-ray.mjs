import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';
import vue from '@vitejs/plugin-vue';

export async function prepareNormalRay(root){
 const source=path.join(root,'examples/normal-ray');
 const target=path.join(root,'research/realization-tower');
 // Only this generated subdirectory is cleared. Never empty the research root.
 const output=path.join(target,'normal-ray-viewer');
 await build({configFile:false,root:source,base:'./',plugins:[vue()],logLevel:'warn',
  build:{outDir:output,emptyOutDir:true,target:'es2022'}});
 await fs.copyFile(path.join(root,'node_modules/three/LICENSE'),path.join(output,'THREE-LICENSE.txt'));
 await fs.copyFile(path.join(root,'node_modules/vue/LICENSE'),path.join(output,'VUE-LICENSE.txt'));
 const html=await fs.readFile(path.join(output,'index.html'),'utf8');
 await fs.writeFile(path.join(target,'normal-ray.html'),'<!-- Generated by scripts/prepare-normal-ray.mjs; edit examples/normal-ray/. -->\n'+html.replaceAll('./assets/','./normal-ray-viewer/assets/'));
}
