import assert from 'node:assert/strict'
import { access, readFile } from 'node:fs/promises'
import test from 'node:test'

const read = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8')
const inventory = JSON.parse(await read('src/data/results-physics.json'))
const index = await read('docs/results-page.md')
const publishedIndex = await read('website/research/results/index.md')
const config = await read('website/.vitepress/config.mts')
const slugs = ['witness-continuation-admission', 'su32-native-record-comparisons', 'ramsey-history-covariant-readers', 'coherent-dependent-four-return', 'cellulation-order-and-source-roles']

function requireEntry(slug, entries = inventory) {
  const matches = entries.filter(entry => entry.slug === slug)
  assert.equal(matches.length, 1, `Expected exactly one curated result: ${slug}`)
  return matches[0]
}

test('new result families have unique, scoped canonical entries and existing source/checker paths', async () => {
  assert.equal(new Set(inventory.map(entry => entry.slug)).size, inventory.length)
  for (const slug of slugs) {
    const entry = requireEntry(slug)
    assert(entry.status && entry.domain)
    for (const heading of ['Reported result', 'Controls and exclusions', 'First unresolved obligation', 'Verification and sources']) {
      assert(entry.details.includes(`## ${heading}`), `${slug}: missing ${heading}`)
    }
    assert.match(entry.details, /not rerun|not replayed/)
    assert.equal(entry.result, null, 'Do not advertise an ignored receipt as a public download')
    for (const checker of entry.checker.split('; ')) await access(new URL(`../${checker}`, import.meta.url))
    const sources = [...entry.details.matchAll(/https:\/\/github\.com\/andrey-kokoev\/marici\/blob\/main\/(research\/[^)\s]+)/g)]
    assert(sources.length > 0, `${slug}: missing research source`)
    for (const [, source] of sources) await access(new URL(`../${source}`, import.meta.url))
  }
})

test('missing curation is rejected rather than treated as an empty result', () => {
  assert.throws(() => requireEntry(slugs[0], []), /Expected exactly one curated result/)
})

test('each result is discoverable through the canonical and generated index and current sidebar', () => {
  for (const slug of slugs) {
    for (const text of [index, publishedIndex]) assert(text.includes(`/research/results/${slug}`), slug)
  }
  assert(config.includes('/research/results/#new-results-frontier-october-2026'))
})

test('generated pages contain their exact canonical details and stated status', async () => {
  for (const slug of slugs) {
    const entry = requireEntry(slug)
    const page = await read(`website/research/results/${slug}.md`)
    assert(page.startsWith('<!-- Generated by scripts/prepare-website.mjs.'))
    assert(page.includes(entry.details), slug)
    assert(page.includes(`**${entry.status}**`), slug)
  }
})

test('formal, live-runtime and blocked-construction boundaries remain separate', () => {
  assert.match(requireEntry(slugs[0]).details, /atomic.*E-envelope/s)
  assert.match(requireEntry(slugs[0]).details, /active endpoint B.*distinguishable points.*propositional/s)
  assert.match(requireEntry(slugs[1]).details, /nativeSignalExecuted.*false/)
  assert.match(requireEntry(slugs[2]).details, /24.*one-step/s)
  assert.match(requireEntry(slugs[2]).details, /arbitrary-length geometry/)
  assert.match(requireEntry(slugs[3]).details, /may be empty/)
  const shell = requireEntry(slugs[4]).details
  for (const phrase of ['406', '155,117,520', '24 arrival', '2,000', 'weaker model', '0 of 30', 'blocked, not repaired']) assert(shell.includes(phrase), phrase)
})
