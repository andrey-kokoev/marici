"""Audit existing rung transport readout before assigning q,p,t.

Uses the existing 137-row fixture and its declared incoming-promotion rule.
The hostile permutes values within the Row interface; it is NOT claimed to
be generated by native seed constructors or shared-leg matrix factorization.
"""
from contextlib import redirect_stdout
from dataclasses import replace
from fractions import Fraction as F
from itertools import combinations
from pathlib import Path
import io
import json
import runpy
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
with redirect_stdout(io.StringIO()):
    fixture = runpy.run_path(str(HERE / "check_rung_transport_diagram.py"))

source = fixture["source"]
mean = fixture["mean"]
promote = fixture["incoming_promotion"]
leaves = fixture["leaves"]
reference = fixture["physical_reference"].value
add, scale = fixture["add"], fixture["scale"]


def flatten(matrix):
    return tuple(x for row in matrix for x in row)


def readout(rows):
    return add(mean(rows), scale(-1, reference))


def covariance(rows):
    center = flatten(mean(rows))
    mass = sum(r.mass for r in rows)
    out = [[F(0) for _ in center] for _ in center]
    for row in rows:
        delta = tuple(x-y for x, y in zip(flatten(row.value), center))
        for i in range(len(center)):
            for j in range(len(center)):
                out[i][j] += F(row.mass, mass) * delta[i] * delta[j]
    return tuple(tuple(row) for row in out)


def trace(matrix):
    return sum(matrix[i][i] for i in range(len(matrix)))


def target_profile(rows):
    groups = fixture["indexed"](rows, "target")
    return {key: (sum(r.mass for r in members), mean(members))
            for key, members in groups.items()}


def profile_covariance(profile):
    # The next incoming-promotion covariance factors through this labelled
    # family profile. No history, representative, or hidden state is chosen.
    mass = sum(m for m, _ in profile.values())
    center = tuple(sum(F(m, mass) * flatten(v)[i] for m, v in profile.values())
                   for i in range(4))
    return tuple(tuple(sum(F(m, mass) * (flatten(v)[i]-center[i]) *
                           (flatten(v)[j]-center[j]) for m, v in profile.values())
                       for j in range(4)) for i in range(4))


checks = []


def check(label, condition):
    if not condition:
        raise AssertionError(label)
    checks.append(label)


profiles = {}
for policy in ("inherited", "common"):
    rows = source
    steps = []
    for depth in range(4):
        check(f"{policy}/{depth}/mean-conserved", readout(rows) == readout(source))
        check(f"{policy}/{depth}/leaves-recovered", leaves(rows) == source)
        next_rows = promote(rows, depth + 1, policy)
        check(f"{policy}/{depth}/family-profile-suffices",
              covariance(next_rows) == profile_covariance(target_profile(rows)))
        steps.append({"promotion_count": depth, "rows": len(rows),
                      "readout": [[str(x) for x in row] for row in readout(rows)],
                      "response_variance": str(trace(covariance(rows)))})
        rows = next_rows
    profiles[policy] = steps

# Freeze ONE generator. Change only incidence/value attachment in its declared
# Row-domain, while preserving the entire unlabelled value multiset.
policy = "inherited"
next_source = promote(source, 1, policy)
witness = None
for i, j in combinations(range(len(source)), 2):
    if source[i].target == source[j].target or source[i].value == source[j].value:
        continue
    hostile = list(source)
    hostile[i] = replace(source[i], value=source[j].value)
    hostile[j] = replace(source[j], value=source[i].value)
    hostile = tuple(hostile)
    next_hostile = promote(hostile, 1, policy)
    if covariance(next_hostile) != covariance(next_source):
        witness = i, j, hostile, next_hostile
        break
check("a-fixed-generator-closure-hostile-exists", witness is not None)
i, j, hostile, next_hostile = witness
check("hostile-same-entire-value-multiset", sorted(r.value for r in hostile) == sorted(r.value for r in source))
check("hostile-same-rung4-mean", readout(hostile) == readout(source))
check("hostile-same-current-covariance", covariance(hostile) == covariance(source))
check("hostile-different-next-covariance", covariance(next_hostile) != covariance(next_source))
check("hostile-different-labelled-target-profile", target_profile(hostile) != target_profile(source))
check("hostile-profile-predicts-next", profile_covariance(target_profile(hostile)) == covariance(next_hostile))
# Same promotion index/time convention can be supplied to both states.
# No canonical momentum or physical time is asserted here.
result = {
    "schema": "marici.nima.rung4-readout-descent.v1",
    "status": "pass",
    "checks": checks,
    "fixture": "check_rung_transport_diagram.py: 137 retained shared-leg rows",
    "generator": "existing incoming_promotion; inherited policy frozen for hostile",
    "rung4_reference": "existing supplied 2I",
    "mean_result": "rung4 mean-offset is conserved; its promotion finite difference is zero",
    "covariance_result": "mean plus covariance plus promotion count fails closure on the declared Row domain",
    "sufficient_next_covariance_data": "target-labelled masses and means",
    "policies": profiles,
    "hostile": {
        "swapped_row_indices": [i, j],
        "row_labels": [repr(source[i].label), repr(source[j].label)],
        "targets": [repr(source[i].target), repr(source[j].target)],
        "source_next_variance": str(trace(covariance(next_source))),
        "hostile_next_variance": str(trace(covariance(next_hostile))),
        "native_seed_admissibility": "not established; Row-interface counterexample only",
    },
    "canonical_momentum": None,
    "physical_clock": None,
    "scope": "Readout/projectability audit, not a derived Hamiltonian phase space. Covariance uses matrix entries, not a spatial Gram metric."
}
path = HERE.parent / "results" / "rung4-readout-descent.json"
path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
print(f"PASS: {len(checks)} exact descent checks")
print("Mean readout conserved for both existing promotion policies.")
print(f"Fixed-policy hostile swaps rows {i},{j}; current mean/covariance identical, next covariance differs.")
print("Target-labelled family masses/means exactly predict the next covariance.")
print("Boundary: native admissibility of the hostile, canonical momentum and physical clock remain unproved.")
