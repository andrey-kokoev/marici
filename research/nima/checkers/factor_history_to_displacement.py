def main():
    ROOT = Path(__file__).resolve().parents[3]
    DEST = ROOT / 'research/nima/results/factor-history-to-displacement.json'
    DEST.unlink(missing_ok=True)

    results = {'depths': {}}

    hist = ClockedHistory.initial()
    for depth in range(7):  # 0 … 6
        if depth > 0:
            hist = hist.advance()
        words = [tuple(p.label for p in path.packets) for path in hist.paths]
        displacements = [word_displacement(path) for path in hist.paths]
        run_depth(depth, words, displacements, results)

    # ── Console summary ──────────────────────────────────────────────
    print('Factorisation test:  D = R * H')
    print('  Status codes:')
    print('    PASS      - same carrier => same displacement, linear R exists')
    print('    COLLISION - two words share carrier but differ in displacement')
    print('    INCONSIST - no collision, but no linear R solves D=RH')
    print('    SKIP      - word too short for this carrier')
    print()

    for d, dr in sorted(results['depths'].items()):
        line = f'  depth {d}  ({dr["word_count"]:4d} words)'
        for name, info in sorted(dr['carriers'].items()):
            if info.get('passed') is True:
                tag = 'PASS'
                rsrc = info.get('R_source', '')
                if rsrc == 'explicit':
                    tag = 'PASS*'  # verified by explicit depth-independent reader
            elif info.get('passed') is False:
                st = info.get('status', 'FAIL')
                if st == 'collision':
                    tag = f'COLL({info["pairs_with_mismatched_displacement"]}/{info["pairs_sharing_carrier"]})'
                else:
                    tag = 'INCONS'
            else:
                tag = 'SKIP'
            line += f'  |  {name}: {tag}'
        print(line)

    print()

    # ── Aggregate verdicts ────────────────────────────────────────────
    tested_16d = [dr for dr in results['depths'].values()
                  if dr['carriers']['16d_joint'].get('passed') is not None]
    ok_16d = all(dr['carriers']['16d_joint'].get('passed') is True
                 for dr in tested_16d)
    if ok_16d:
        print('The 16-D joint record determines displacement at every tested depth (1-6).')
    else:
        print('WARNING: 16-D joint record does NOT determine displacement at some depth.')

    ok_8d = all(
        dr['carriers']['8d_source_plus_target'].get('passed') is True
        for dr in results['depths'].values()
        if dr['carriers']['8d_source_plus_target'].get('passed') is not None
    )
    if ok_8d:
        print('The 8-D endpoint joint determines displacement at every tested depth (0-6).')
    else:
        print('WARNING: 8-D endpoint joint does NOT determine displacement at some depth.')

    ok_6d = all(
        dr['carriers']['6d_final_summary'].get('passed') is True
        for dr in results['depths'].values()
        if dr['carriers']['6d_final_summary'].get('passed') is not None
    )
    if ok_6d:
        print('The 6-D final summary determines displacement at every tested depth.')
    else:
        print('The 6-D final summary does NOT always determine displacement.')

    # ── Explicit reader verification ──────────────────────────────────
    print()
    r16 = explicit_reader_16d()
    r8 = explicit_reader_8d()

    # Verify on all depth>=1 words
    errors_16d = 0
    errors_8d = 0
    total_long = 0
    hist = ClockedHistory.initial()
    for depth in range(7):
        if depth > 0:
            hist = hist.advance()
        for path in hist.paths:
            word = tuple(p.label for p in path.packets)
            disp = word_displacement(path)
            total_long += 1

            # 8-D
            h8 = endpoint_joint_8d(word)
            pred8 = tuple(
                sum(h8[i] * r8[axis][i] for i in range(8))
                for axis in range(3)
            )
            if pred8 != disp:
                errors_8d += 1

            # 16-D (only for depth >= 1, i.e. words of length >= 2)
            if len(word) >= 2:
                h16 = carrier_16d(word)
                pred16 = tuple(
                    sum(h16[i] * r16[axis][i] for i in range(16))
                    for axis in range(3)
                )
                if pred16 != disp:
                    errors_16d += 1

    print(f'Explicit reader R_8 verified on all {total_long} words:  '
          f'{errors_8d} errors.')
    print(f'Explicit reader R_16 verified on all words of length >= 2:  '
          f'{errors_16d} errors.')
    print()
    print('Proof sketch:')
    print('  R_16 * h_16(w) = V_target(w[-1]) + (-V_source(w[0]))')
    print('                 = V_target(w[-1]) - V_source(w[0])')
    print('                 = displacement(w)')
    print('  This holds for every composable word of length >= 2.')
    print()
    print('  R_8 * h_8(w)  = -V_source(w[0]) + V_target(w[-1])')
    print('                 = displacement(w)')
    print('  This holds for every word of length >= 1.')

    # ── Original 42/46 reproduction ──────────────────────────────────
    d3 = results['depths'][3]
    d3_words = []
    d3_disp = []
    hist = ClockedHistory.initial()
    for _ in range(3):
        hist = hist.advance()
    for path in hist.paths:
        d3_words.append(tuple(p.label for p in path.packets))
        d3_disp.append(word_displacement(path))

    six_groups = defaultdict(list)
    for i, w in enumerate(d3_words):
        s6 = carrier_6d(w)
        six_groups[s6].append(i)

    pairs_same6_diff10_diffD = 0
    pairs_same6_diff10_sameD = 0
    examples_sameD = []
    for s6, idxs in six_groups.items():
        for i in range(len(idxs)):
            for j in range(i + 1, len(idxs)):
                a, b = idxs[i], idxs[j]
                c10a = carrier_10d(d3_words[a])
                c10b = carrier_10d(d3_words[b])
                if c10a == c10b:
                    continue
                da = d3_disp[a]
                db = d3_disp[b]
                if da == db:
                    pairs_same6_diff10_sameD += 1
                    if len(examples_sameD) < 4:
                        examples_sameD.append({
                            'a': d3_words[a], 'b': d3_words[b],
                            'disp': [str(x) for x in da],
                            '6d_summary': str([str(s) for s in s6]),
                            '10d_a': str(c10a), '10d_b': str(c10b),
                        })
                else:
                    pairs_same6_diff10_diffD += 1

    results['depth3_reproduce_original'] = {
        'total_pairs_same6d_diff10d': pairs_same6_diff10_diffD + pairs_same6_diff10_sameD,
        'pairs_with_diff_displacement': pairs_same6_diff10_diffD,
        'pairs_with_same_displacement': pairs_same6_diff10_sameD,
        'examples_sameD': examples_sameD,
    }
    print()
    print(f'depth 3 reproduce: '
          f'{pairs_same6_diff10_diffD + pairs_same6_diff10_sameD} pairs sharing '
          f'6D summary and differing in 10D carrier')
    print(f'  {pairs_same6_diff10_diffD} have different displacement, '
          f'{pairs_same6_diff10_sameD} have same displacement')
    if examples_sameD:
        print(f'  Same-displacement examples (different internal paths, same endpoints):')
        for ex in examples_sameD:
            print(f'    {ex["a"]}  ~  {ex["b"]}  ->  {ex["disp"]}')

    results['interpretation'] = (
        "A carrier 'PASS' means ker(H) subset ker(D): the retained data "
        "determines displacement uniquely, so a linear map from carrier to R^3 "
        "exists. 'COLLISION' means two words share a carrier value but have "
        "different displacement — this is a definitive obstruction. "
        "'INCONSIST' means no collision occurred, yet no linear map exists "
        "for ALL observed carriers (the rank condition fails). "
        "The explicit readers R_8 and R_16 are verified depth-independent "
        "constructors; they prove existence directly without solving."
    )

    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(json.dumps(results, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()