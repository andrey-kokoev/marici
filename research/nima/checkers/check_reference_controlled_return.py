"""Joint reversible check for supplied reference flips and controlled return.

A=alpha J, B=beta J, so the edge mixer is L_s=s L with s=alpha*beta.
The flip instruction is supplied, not generated by the carrier or by WG.
"""
from fractions import Fraction as F
from pathlib import Path
import json
import hashlib
from check_four_packet_cycle import UNIT,E2,tensor,rotate,MAX_DEPTH
from check_four_packet_record_feedback import (
    basis,matrix_of,mm,transpose,readout,left_rotate,exchange,scale,budget,
)
ROOT=Path(__file__).resolve().parents[1]


def U(sign,v):
    return sum(exchange(rotate(v[:4]),scale(left_rotate(v[4:]),sign)),())


def Uinv(sign,v):
    x,t=exchange(v[:4],v[4:])
    return rotate(x)+scale(left_rotate(t),sign)


def step(alpha,beta,v,flip_side):
    assert flip_side in ('none','A','B')
    aa=-alpha if flip_side=='A' else alpha
    bb=-beta if flip_side=='B' else beta
    return aa,bb,U(aa*bb,v)


def undo(alpha,beta,v,flip_side):
    old=Uinv(alpha*beta,v)
    return (-alpha if flip_side=='A' else alpha),(-beta if flip_side=='B' else beta),old


def main():
    I=tuple(basis(20));matrices={s:matrix_of(lambda v:U(s,v),20) for s in (F(1),F(-1))}
    for s,M in matrices.items():
        V=matrix_of(lambda v:Uinv(s,v),20)
        assert mm(transpose(M),M)==I and mm(V,M)==mm(M,V)==I
    # Both reference signs have fixed squared Frobenius norm 2 each.
    for a in (F(1),F(-1)):
        for b in (F(1),F(-1)):
            for event in ('none','A','B'):
                for v in basis(20):
                    new=step(a,b,v,event)
                    assert undo(*new,event)==(a,b,v)
                    assert budget(new[2][:4],new[2][4:])+4==budget(v[:4],v[4:])+4
    C=tuple(zip(*(readout(e) for e in basis(16))))
    X=tuple(tuple(F(i==j) for j in range(20)) for i in range(4))
    O=X+tuple((F(0),)*4+row for row in C)
    reports=[]
    # Fixed supplied protocol: flip A before every exchange. Starting at s,
    # the two-step body map is U_s U_-s and references then return.
    for s in (F(1),F(-1)):
        T=mm(matrices[s],matrices[-s]);power=I;full=[];observed=[]
        for n in range(1,7):
            power=mm(T,power)
            if power==I:full.append(2*n)
            if mm(O,power)==O:observed.append(2*n)
        assert full==[12] and observed==[6,12]
        T3=mm(mm(T,T),T)
        assert T3!=I and 20-rank_difference(T3,I)==12
        reports.append(dict(initial_relative_sign=str(s),numerical_period=12,observed_period=6,
                            retained_residual_sign_reverses_at_six=True))
    # Retain the supplied event history; numerical recurrence does not erase it.
    histories=[]
    for t in (tensor(UNIT,UNIT),tensor(E2,E2)):
        state=(F(1),F(1),UNIT+t);original=state;parents=[];events=[]
        for n in range(MAX_DEPTH):
            parents.append(state);events.append('A')
            state=step(*state,'A')
            assert budget(state[2][:4],state[2][4:])==2
        assert len(events)==MAX_DEPTH==3 and len(parents)==3
        for prior,event in zip(reversed(parents),reversed(events)):
            state=undo(*state,event);assert state==prior
        assert state==original
        histories.append(dict(recovered_by_inverse=True,retained_events=len(events)))
    result=dict(schema='marici.nima.reference-controlled-return.v1',status='pass',
        coupling='Given A=alpha J and B=beta J, replace L by (alpha*beta)L; flip the specified reference before exchange.',
        controls=['none','flip A','flip B'],all_signs_and_basis_inverse_checked=True,
        conserved_budget='||x||^2+||t||^2+||A||_F^2+||B||_F^2 (reference contribution=4)',
        repeated_flip_protocol=reports,fixture_histories=histories,
        disposition='The declared reference-control protocol composes reversibly with the prior exchange and conserves the joint coefficient budget. Repeated single-reference flipping has numerical period 12 but observed period 6; histories remain retained.',
        limits='Control events and initial reference are supplied. This is not a WG-selected autonomous coupling or physical clock. It applies to the +/-J reference family, not arbitrary evolving references. Fixture traces retain the prior three-advance bound; twelve-step return is an operator identity, not admission to execute beyond that bound. Numerical 12 is not a derivation of the old gravitational prefactor.',
        source_sha256={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in (
            'checkers/check_four_packet_record_feedback.py','checkers/check_reference_alignment_preparation.py',
            'checkers/check_reference_controlled_return.py')})
    (ROOT/'results/reference-controlled-return.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))


def rank_difference(a,b):
    from check_four_packet_record_feedback import rank,sub
    return rank(tuple(sub(x,y) for x,y in zip(a,b)))


if __name__=='__main__':main()
