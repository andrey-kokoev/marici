// Export only freshly replayed witnesses; never edit the research receipts.
import {readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const assets={};
for(const [name,id] of [['n15','nitrogen15-local'],['o16','oxygen16-local'],['o17','oxygen17-local'],['o18','oxygen18-local'],['f19','fluorine19-local'],['ne20','neon20-local'],['ne22','neon22-local']]){
 const check=spawnSync(process.execPath,[`research/strominger/checkers/check_reference_${name}.mjs`],{encoding:'utf8'});assert.equal(check.status,0,check.stderr);
 const base=`research/strominger/results/reference-${name}-search`,summary=JSON.parse(await readFile(base+'/verification.json')),row=summary.rows.find(r=>r.witnessFile),bytes=await readFile(base+'/'+row.witnessFile),saved=JSON.parse(bytes),replay=JSON.parse(await readFile(base+'/replay-verification.json'));
 assert.equal(createHash('sha256').update(bytes).digest('hex'),replay.witnessSha256);
 assets[id]={target:summary.target,maxOrigin:saved.maxOrigin,witness:saved.witness,witnessSha256:replay.witnessSha256,source:base+'/'+row.witnessFile};
}
await writeFile('research/strominger/demos/particle-overlap-tetrahedron/local-reference-data.mjs','// Generated by checkers/export_local_reference_viewer.mjs after fresh replay.\nexport const localReferences='+JSON.stringify(assets)+';\n');
// Package source rules for the standalone public route. Only import paths
// change; other-owner originals remain untouched.
const demo='research/strominger/demos/particle-overlap-tetrahedron/';
const rules=await readFile('research/nima/generative-phase-assembly.mjs','utf8');
await writeFile(demo+'local-reference-rules.mjs',rules.replaceAll('../strominger/demos/particle-overlap-tetrahedron/','./'));
const universe=await readFile('research/nima/origin-bounded-assemblies.mjs','utf8');
await writeFile(demo+'local-reference-universe.mjs',universe.replace("'./generative-phase-assembly.mjs'","'./local-reference-rules.mjs'"));
console.log('Exported N-15, O-16, O-17, O-18, F-19, Ne-20 and Ne-22 local-reference witnesses and source-rule snapshots');
