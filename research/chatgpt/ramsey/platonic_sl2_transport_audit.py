"""Exact algebra and finite-quotient checks for the 3R/7B Platonic-flow model.

R and B are nilpotent components of M, while U=exp(R) and V=exp(B)
are invertible candidate transport operations. No physical arrow successor rule
or 3R/7B itinerary is assumed to follow from the matrices.
"""

from collections import Counter, deque
from itertools import product
import sympy as sp


def matmul_mod(A, B, n):
    a, b, c, d = A
    e, f, g, h = B
    return ((a*e+b*g) % n, (a*f+b*h) % n,
            (c*e+d*g) % n, (c*f+d*h) % n)


def generated_group(n):
    identity = (1, 0, 0, 1)
    generators = ((1, n-1, 0, 1), (1, 0, 1, 1))
    seen = {identity}
    queue = deque([identity])
    while queue:
        x = queue.popleft()
        for gen in generators:
            y = matmul_mod(x, gen, n)
            if y not in seen:
                seen.add(y)
                queue.append(y)
    return seen


def matrix_order(A, nmax=12):
    identity = sp.eye(2)
    power = identity
    for k in range(1, nmax+1):
        power = power*A
        if power == identity:
            return k
    return None


def frame_word(gaps, U, V):
    r, s, t = gaps
    return U*V**r*U*V**s*U*V**t


def main():
    a = sp.symbols('a')
    R = sp.Matrix([[0, -a], [0, 0]])
    B = sp.Matrix([[0, 0], [a, 0]])
    N = -B*R
    M = R+B+N
    U = sp.eye(2)+R
    V = sp.eye(2)+B
    assert R*R == B*B == sp.zeros(2)
    assert N*N == a*a*N
    assert sp.simplify(N+(V-sp.eye(2))*(U-sp.eye(2))) == sp.zeros(2)
    assert sp.simplify(M-U*V-(a*a-1)*sp.eye(2)) == sp.zeros(2)
    assert sp.simplify(U*V*U-V*U*V - a*(a*a-1)*sp.Matrix([[0,1],[1,0]])) == sp.zeros(2)
    print('General a: N=-(V-I)(U-I); N^2=a^2*N; M-UV=(a^2-1)*I.')
    print('Braid defect UVU-VUV = a(a^2-1) [[0,1],[1,0]].')

    U = U.subs(a, 1)
    V = V.subs(a, 1)
    S = U*V*U
    T = U*V
    assert S**2 == -sp.eye(2)
    assert T**3 == -sp.eye(2)
    assert S.inv()*T == U.inv()
    assert S*U*S.inv() == V and S*V*S.inv() == U
    print('\na=1: S^2=T^3=-I, S^-1*T=U^-1, S swaps U and V by conjugation.')

    seen = set()
    table = []
    for r in range(8):
        for s in range(8-r):
            t = 7-r-s
            choices = ((r,s,t), (s,t,r), (t,r,s))
            representative = min(choices)
            if representative in seen:
                continue
            seen.add(representative)
            W = frame_word(representative, U, V)
            trace = sp.trace(W)
            assert trace == 1-sp.prod(x-2 for x in representative)
            table.append((representative, trace, matrix_order(W)))
    assert len(table) == 12
    assert sum(order is not None for _, _, order in table) == 5
    print('\nCyclic 3R/7B patterns (R B^r R B^s R B^t, r+s+t=7):')
    print('gaps         trace   frame-order')
    for gaps, trace, order in sorted(table):
        print(f'{str(gaps):12} {str(trace):>5}   {str(order or "infinite"):>8}')

    print('\nCongruence groups generated by U,V:')
    for n in (3,4,5):
        group = generated_group(n)
        # The action of the central subgroup {I,-I} identifies each pair.
        projective = set()
        for x in group:
            neg_x = tuple((-z) % n for z in x)
            projective.add(min(x, neg_x))
        print(f'mod {n}: SL-image size {len(group)}, projective size {len(projective)}')

if __name__ == '__main__':
    main()
