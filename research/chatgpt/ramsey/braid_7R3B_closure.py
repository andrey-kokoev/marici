#!/usr/bin/env python3
"""Exact 3-strand braid return calculation for two 7R/3B trips.

MODEL ASSUMPTIONS:
 * R and B mean positive braid generators sigma_1 and sigma_2.
 * Each 10-letter trip has seven R and three B, with no adjacent B.
 * The two trips are joined with no adjacent B across their junction.
 * The turnaround makes the second leg act as the inverse word w2^(-1).
 * Additional moves may be R,B and their inverses r,b; their cost is 1.
 * We require braid identity, not just SL(2,Z) matrix identity.
 * Framing twists, FCC incidence, and visiting all spatial arrows are not tested.

The faithful invariant for B_3 used here is (matrix, exponent_sum):
 B_3 -> SL(2,Z), with kernel generated by (sigma_1 sigma_2)^6,
 whose exponent sum is 12. The pair distinguishes kernel elements.
"""
from collections import Counter, deque
from itertools import combinations

I = (1, 0, 0, 1)
R = (1, -1, 0, 1)
B = (1, 0, 1, 1)
r = (1, 1, 0, 1)
b = (1, 0, -1, 1)
GENERATORS = (("R", R, 1), ("B", B, 1), ("r", r, -1), ("b", b, -1))

def multiply(a, c):
    x, y, z, w = a
    p, q, s, t = c
    return (x*p + y*s, x*q + y*t, z*p + w*s, z*q + w*t)

def inverse(a):
    x, y, z, w = a
    return (w, -y, -z, x)

def image(word):
    m, exponent = I, 0
    for letter in word:
        g = next(item for name, *item in GENERATORS if name == letter)
        mat, sign = g
        m = multiply(m, mat)
        exponent += sign
    return m, exponent

WORDS = []
for B_positions in combinations(range(10), 3):
    if any(j == i + 1 for i, j in zip(B_positions, B_positions[1:])):
        continue
    WORDS.append("".join("B" if i in B_positions else "R" for i in range(10)))

WORD_MATRICES = {w: image(w)[0] for w in WORDS}
PAIRS = [(x, y) for x in WORDS for y in WORDS
         if not (x[-1] == "B" and y[0] == "B")]

# Closing word C satisfies w1 * inverse(w2) * C = 1, so C = w2 * inverse(w1).
TARGETS = {multiply(WORD_MATRICES[y], inverse(WORD_MATRICES[x]))
           for x, y in PAIRS}
START = (I, 0)
parents = {START: None}
distances = {START: 0}
queue = deque([START])
unfound = set(TARGETS)
unfound.discard(I)
while unfound:
    matrix, exponent = queue.popleft()
    for letter, generator, sign in GENERATORS:
        point = (multiply(matrix, generator), exponent + sign)
        if point in distances:
            continue
        distances[point] = distances[(matrix, exponent)] + 1
        parents[point] = ((matrix, exponent), letter)
        queue.append(point)
        if point[1] == 0:
            unfound.discard(point[0])

histogram = Counter(distances[(multiply(WORD_MATRICES[y], inverse(WORD_MATRICES[x])), 0)]
                    for x, y in PAIRS)
maximum = max(histogram)
print("Trip words:", len(WORDS), "; allowed ordered trip pairs:", len(PAIRS))
print("Shortest return lengths and counts:", dict(sorted(histogram.items())))
print("Maximum shortest completion:", maximum)

for w1, w2 in PAIRS:
    goal = (multiply(WORD_MATRICES[w2], inverse(WORD_MATRICES[w1])), 0)
    if distances[goal] == maximum:
        result = []
        current = goal
        while current != START:
            parent, letter = parents[current]
            result.append(letter)
            current = parent
        completion = "".join(reversed(result))
        inverted_w2 = "".join({"R": "r", "B": "b"}[ch] for ch in reversed(w2))
        assert len(completion) == maximum
        assert image(w1 + inverted_w2 + completion) == (I, 0)
        print("Witness:", w1, "then", inverted_w2, "then", completion)
        print("(Lowercase letters are inverse braid generators.)")
        break
