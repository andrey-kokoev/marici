def main():
    for i, code in enumerate(R34):
        n, edges = decode_graph6(code)
        f, h = betti(n, edges, 2)
        b, _ = boundary_support(n, edges, 3)
        assert f in ([8,17,10], [8,18,12], [8,16,8])
        print('R34 graph', i + 1, 'blue f-vector', f, 'F2 Betti', h, 'boundary edges', b)

    n, edges = decode_graph6(R35)
    assert betti(n, edges, 3) == ([13,52,78,39], [1,0,0,1])
    assert boundary_support(n, edges, 4)[0] == 0
    print('R35 sphere f, Betti', betti(n, edges, 3))
    print('R35 sphere shelling counts', shelling_check(n, edges, SHELLING_R35))

    # Every four-regular undirected circulant on Z13 is generated by two
    # distinct steps a,b in {1,...,6}. This is an exhaustive 15-case test.
    print('Z13: steps, red-triangle count, blue-K5 count, Stokes boundary size')
    success = []
    for a, b in combinations(range(1, 7), 2):
        red = {(min(i, (i + s) % 13), max(i, (i + s) % 13))
               for i in range(13) for s in (a,b)}
        redtri = sum(all(pair in red for pair in combinations(t,2)) for t in combinations(range(13),3))
        blue5 = len(blue_simplices(13, red, 5))
        bdry, tetra = boundary_support(13, red, 4)
        print(f' ({a},{b})  {redtri:2}  {blue5:2}  {bdry:2}')
        assert (bdry == 0) == ((a*a+b*b) % 13 == 0)
        assert (bdry == 0) == (redtri == 0 and blue5 == 0)
        if bdry == 0:
            success.append((a,b))
    assert success == [(1,5), (2,3), (4,6)]

    # Three tetrahedral shift orbits; the reduced F2 boundary matrix has
    # rank 2 and kernel spanned by (1,1,1).
    seeds = [(0,2,4,6), (0,2,6,9), (0,3,6,9)]
    blue_facets = set(blue_simplices(13, {(min(i,(i+s)%13), max(i,(i+s)%13))
                       for i in range(13) for s in (1,5)}, 4))
    orbits = [{tuple(sorted((v+k)%13 for v in seed)) for k in range(13)} for seed in seeds]
    assert all(len(orb)==13 for orb in orbits)
    assert not any(orbits[i] & orbits[j] for i,j in combinations(range(3),2))
    assert set().union(*orbits) == blue_facets
    tri = sorted({face for t in blue_facets for face in combinations(t,3)})
    tri_orbits = []
    pending = set(tri)
    while pending:
        t = min(pending)
        orb = {tuple(sorted((v+k)%13 for v in t)) for k in range(13)}
        tri_orbits.append((t,orb))
        pending -= orb
    assert len(tri_orbits) == 6
    columns = []
    for seed in seeds:
        tri_types = Counter(next(i for i, (_, orb) in enumerate(tri_orbits) if f in orb)
                            for f in combinations(seed,3))
        columns.append(sum(1<<i for i, c in tri_types.items() if c%2))
    assert rank_f2(columns) == 2 and columns[0] ^ columns[1] ^ columns[2] == 0
    print('R35 3 shift-orbit boundary columns (bitmasks)', columns, 'rank', rank_f2(columns))

    print('R36 17-node critical colorings: blue f-vector, F2 Betti')
    for code in R36:
        n, red = decode_graph6(code)
        f, hom = betti(n, red, 4)
        print(' ', f, hom)
        assert hom[4] == 0 and hom[3] in (1,2,3)

    # Testing the square-root-of-negative-one rule beyond 13.
    p, r = 17, 4
    assert (r*r+1) % p == 0
    red = {(min(i,(i+s)%p), max(i,(i+s)%p)) for i in range(p) for s in (1,r)}
    K6 = len(blue_simplices(p, red, 6))
    assert K6 == 34
    print('Z17 steps 1,4: blue K6 count =', K6, '(not Ramsey admissible)')

if __name__ == '__main__':
    main()

# Additional tests for the non-cyclic star-cluster obstruction.
# Known theorem (Barmak): the union of stars of any face of a flag complex
# is contractible. A face meeting all maximal faces would make the whole
# complex contractible. A nonzero top homology class also excludes a face
# meeting all top-dimensional faces, even when the complex is non-pure.

def extension_deficit(n, red, top_size):
    """Minimum number of top blue simplices disjoint from a blue clique.
    It suffices to check maximal blue cliques: any smaller face extends to one.
    """
    top = [set(s) for s in blue_simplices(n, red, top_size)]
    maximal = []
    for size in range(1, top_size + 1):
        for s in blue_simplices(n, red, size):
            ss = set(s)
            if not any(ss < set(t) for bigger_size in range(size + 1, top_size + 1)
                       for t in blue_simplices(n, red, bigger_size)):
                maximal.append(s)
    candidates = [(sum(not set(s) & t for t in top), s) for s in maximal]
    return min(n for n, _ in candidates), candidates, maximal


def additional_tests():
    print('\nNon-cyclic extension and top-homology checks:')
    expected_r34 = [1,3,3]
    for i, code in enumerate(R34):
        n, red = decode_graph6(code)
        min_gap, _, maximal = extension_deficit(n, red, 3)
        assert min_gap == expected_r34[i]
        assert all(len(f) == 3 for f in maximal), 'R34 blue complex not pure'
        _, bettis = betti(n, red, 2)
        print(f'R(3,4) graph {i+1}: minimum disjoint blue triangles={min_gap}; '
              f'maximal-face sizes={set(map(len,maximal))}; Betti={bettis}')

    n, red = decode_graph6(R35)
    min_gap, _, maximal = extension_deficit(n, red, 4)
    assert min_gap == 11
    assert all(len(f) == 4 for f in maximal)
    assert betti(n, red, 3)[1] == [1,0,0,1]
    print(f'R(3,5) critical graph: minimum disjoint blue tetrahedra={min_gap}; '
          'nonzero top H3 detects nonextension via star cluster + Stokes')

    expected_r36 = [8,10,16,14,12,12,14]
    expected_boundary3 = [42,46,32,44,30,62,54]
    for i, code in enumerate(R36):
        n, red = decode_graph6(code)
        min_gap, _, maximal = extension_deficit(n, red, 5)
        assert min_gap == expected_r36[i]
        f, bettis = betti(n, red, 4)
        assert bettis[4] == 0 and bettis[3] > 0
        border, _ = boundary_support(n, red, 5)
        assert border == expected_boundary3[i]
        print(f'R(3,6) graph {i+1}: deficit={min_gap}; '
              f'boundary tetrahedra={border}; H3={bettis[3]}, H4={bettis[4]}; '
              f'maximal-face sizes={set(map(len,maximal))}')

if __name__ == '__main__':
    additional_tests()
