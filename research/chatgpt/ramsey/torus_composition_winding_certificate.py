"""Torus A/B composition, and exact winding constraints; Python 3 + standard library.

A(i,j) iff cos(theta_i-theta_j)+cos(phi_i-phi_j)<-1.
The rational circle parametrization certifies A/B incidences exactly.
For any closed A-cycle of length L, with positive step windings r,s,
cos(2*pi*r/L)+cos(2*pi*s/L)<-1 is necessary and sufficient for
an isolated closed A-path with those winding numbers.
"""
from itertools import combinations
from collections import Counter
from math import atan2, cos, pi

S = 1_000_000
T1 = [-2285936, 863234, -599810, 168418, 872786, -15116831,
      31410691, 21937442, 1095935, -484056, -102848, -154188,
      -786293, 323549, -15813583, 2037981]
T2 = [694747, -294333, -139724, 630411, 2381420, -1146721,
      431377, -476715, 877691, 213913, -538742, 2850188,
      -2110553, 6693725, 6123880, -1433097]
N = len(T1)

def vec(t):
    return (S*S-t*t, 2*S*t, S*S+t*t)

U = list(map(vec, T1))
V = list(map(vec, T2))
A = [[False] * N for _ in range(N)]
for i, j in combinations(range(N), 2):
    u, v = U[i], U[j]
    x, y = V[i], V[j]
    dc1 = u[0]*v[0] + u[1]*v[1]
    dc2 = x[0]*y[0] + x[1]*y[1]
    prod = u[2]*v[2]*x[2]*y[2]
    value = prod + dc1*x[2]*y[2] + dc2*u[2]*v[2]
    assert value != 0
    A[i][j] = A[j][i] = value < 0

assert sum(A[i][j] for i,j in combinations(range(N), 2)) == 37
assert all(not all(A[i][j] for i,j in combinations(tri,2))
           for tri in combinations(range(N),3))
assert all(any(A[i][j] for i,j in combinations(six,2))
           for six in combinations(range(N),6))

primitive = [(i,j) for i,j in combinations(range(N),2)
             if not A[i][j] and
             not any(A[i][k] and A[k][j] for k in range(N))]
assert primitive == [(6,9),(7,8)]

def cycles(L):
    adj = [[j for j in range(N) if A[i][j]] for i in range(N)]
    out = []
    def dfs(path):
        if len(path) == L:
            if A[path[-1]][path[0]] and path[1] < path[-1]:
                out.append(tuple(path))
            return
        for v in adj[path[-1]]:
            if v > path[0] and v not in path:
                dfs(path + [v])
    for v in range(N):
        for w in adj[v]:
            if w>v: dfs([v,w])
    return out

theta = [atan2(v[1],v[0]) for v in U]
phi = [atan2(v[1],v[0]) for v in V]

def winding(path, angles):
    L = len(path)
    increments = [(angles[path[(i+1)%L]] - angles[path[i]]) % (2*pi)
                  for i in range(L)]
    assert all(pi/2 < d < 3*pi/2 for d in increments)
    raw = sum(increments)/(2*pi)
    r = round(raw)
    assert abs(raw-r) < 1.e-8
    return r

print('16-node two-circle witness: A-edges=37, B-edges=83')
print('B-pairs not generated by a two-step A path:', primitive)
for L in (4,5,6,7):
    examples = cycles(L)
    types = Counter()
    for path in examples:
        r,s = winding(path, theta), winding(path, phi)
        assert cos(2*pi*r/L)+cos(2*pi*s/L) < -1-1e-8
        types[(r,s)] += 1
    print('A-cycles of length',L,':',len(examples),'winding-pair counts:',dict(sorted(types.items())))
print('ALL CHECKS PASSED')
