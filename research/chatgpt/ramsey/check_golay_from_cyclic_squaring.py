#!/usr/bin/env python3
"""Finite exact tests of the proposed Golay/Ramsey cyclic-closure bridge.

Builds no Golay matrix by hand. Factors x^n+1 over F_2 by polynomial division,
then uses a degree-11 factor to derive the 23 cyclic syndrome columns.

The 23-position carrier and GF(2) arithmetic are specified mathematical choices;
no derivation of 23 positions from the seven-symbol input is claimed.
"""
from itertools import combinations
from math import comb


def deg(x): return x.bit_length() - 1


def rem(a, b):
    while a and deg(a) >= deg(b):
        a ^= b << (deg(a)-deg(b))
    return a


def mul(a,b,mod):
    z=0
    while b:
        if b & 1: z ^= a
        a <<= 1
        if a >> deg(mod): a ^= mod
        b >>= 1
    return z


def xor_orbit_sum(word,n):
    mask=(1<<n)-1
    x=word;out=0
    for _ in range(n):
        out ^= x
        x=((x<<1)&mask)|(x>>(n-1))
    return out


def divisors_degree_n(n,d):
    polynomial=(1<<n)|1  # x^n+1 in characteristic two
    return [f for f in range((1<<d)|1,1<<(d+1),2) if rem(polynomial,f)==0]


def cyclic_syndromes(n, f):
    v=1
    out=[]
    for _ in range(n):
        out.append(v)
        v=mul(v,2,f)
    assert v==1 and len(set(out))==n
    return out


def syndrome_sphere(columns,r=3):
    groups={}
    count=0
    for t in range(r+1):
        for inds in combinations(range(len(columns)),t):
            value=0
            for i in inds: value ^= columns[i]
            if value in groups:
                return False,count,(groups[value],inds,value)
            groups[value]=inds
            count+=1
    return True,count,groups


def rank(vectors):
    pivots={}
    for v in vectors:
        while v:
            bit=deg(v)
            if bit not in pivots:
                pivots[bit]=v
                break
            v ^= pivots[bit]
    return len(pivots)



def poly_mul(a,b):
    out=0
    while b:
        if b&1: out ^= a
        a <<= 1
        b >>= 1
    return out


def test_witt_designs(f):
    # The ideal generated by f has 4096 words of length 23; no Golay table is used.
    code=[poly_mul(f,h) for h in range(1<<12)]
    assert len(set(code))==4096 and max(code)<1<<23
    from collections import Counter
    weights=Counter(c.bit_count() for c in code)
    assert weights=={0:1,7:253,8:506,11:1288,12:1288,15:506,16:253,23:1}

    heptads=[tuple(i for i in range(23) if c&(1<<i))
             for c in code if c.bit_count()==7]
    assert len(heptads)==253
    fourths={}
    for heptad in heptads:
        for quartet in combinations(heptad,4):
            assert quartet not in fourths
            fourths[quartet]=heptad
    assert len(fourths)==comb(23,4)==253*comb(7,4)
    print('S(4,7,23): 253 heptads; each of 8855 four-sets has one completion.')

    # Extend via a parity bit at coordinate 23.
    extended=[c | ((c.bit_count()&1)<<23) for c in code]
    extweights=Counter(c.bit_count() for c in extended)
    assert extweights=={0:1,8:759,12:2576,16:759,24:1}
    octads=[tuple(i for i in range(24) if c&(1<<i))
            for c in extended if c.bit_count()==8]
    fifths={}
    for octad in octads:
        for quintet in combinations(octad,5):
            assert quintet not in fifths
            fifths[quintet]=octad
    assert len(fifths)==comb(24,5)==759*comb(8,5)
    print('S(5,8,24): 759 octads; each of 42504 five-sets has one completion.')

def test():
    assert sum(comb(7,i) for i in range(4))==64
    assert sum(comb(23,i) for i in range(4))==2048
    # binary projection R=1, G=0, empty=0 in RGRGR00
    seed=sum(1<<i for i in (0,2,4))
    assert xor_orbit_sum(seed,7)==0b1111111
    # This averaging output generates the 7-bit repetition code.
    print('7-position RGRGR00: cyclic XOR average = 1111111 (binary R-indicator).')

    f7=divisors_degree_n(7,3)
    f23=divisors_degree_n(23,11)
    print('x^7+1 degree-3 factors:', [hex(f) for f in f7]); assert len(f7)==2
    print('x^23+1 degree-11 factors:', [hex(f) for f in f23]); assert len(f23)==2
    # Reflecting position i <-> -i interchanges these two 11-dimensional factors.
    for f in f23:
        columns=cyclic_syndromes(23,f)
        assert rank(columns)==11
        perfect,count,found=syndrome_sphere(columns)
        assert perfect and count==2048 and len(found)==2048
        assert set(found)==set(range(2048))
        # Every weight-4 syndrome must match one <=3, with disjoint support.
        # Thus we find a 7-point subset whose column sum vanishes.
        four=tuple(range(4))
        syn=0
        for i in four: syn ^= columns[i]
        three=found[syn]
        assert len(three)==3 and set(four).isdisjoint(three)
        seven=tuple(sorted(four+three))
        assert 0==__import__('functools').reduce(lambda a,i: a^columns[i],seven,0)
        print('23-factor',hex(f),'rank 11; all 2048 <=3-syndromes distinct;',
              'seven-point codeword support',seven)
    # No other perfect-volume candidate between 7 and 23.
    for n in range(8,23):
        volume=sum(comb(n,j) for j in range(4))
        assert volume & (volume-1)
    # Order of doubling = 11. A 23-cycle splits as 1+11+11 over GF2.
    o=1
    while pow(2,o,23)!=1:o+=1
    assert o==11
    test_witt_designs(f23[0])
    q=[]; x=1
    for _ in range(11):
        q.append(x);x=x*2%23
    assert len(set(q))==11
    assert set(q).isdisjoint({(23-i)%23 for i in q})
    assert len(set(q)|{(23-i)%23 for i in q}|{0})==23
    print('Doubling orbits on 23 positions: 1 fixed + 11 + 11; reflected orbits exchange.')
    print('PASS: exact cyclic-syndrome perfect packing; not a proof that Ramsey operations force length 23.')

if __name__=='__main__': test()
