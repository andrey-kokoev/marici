#!/usr/bin/env python3
"""Exact pair-loss calculation for a quarter-turn equivariant two-coordinate graph.

Reference: Harris et al., arXiv:2609.01782v1, Lemma 3.2.
For any I of final vertices, L(I)= sum_{x in V_R,V_B} choose(|X_x cap I|, 2).

No asymptotic claim is inferred from the finite graph.
"""
from math import comb
from collections import Counter
import numpy as np
from scipy.optimize import milp, Bounds, LinearConstraint
from scipy.sparse import lil_matrix
import sys
sys.path.insert(0, '/mnt/data')
from ramsey_two_bite_equivariant_matrix import adjacency, mixed_repair, neighbors_from_edges


def pair_loss(I, coords, modulus=13, redD={1,12}, blueD={5,8}):
    rc=Counter(coords[v][0] for v in I)
    bc=Counter(coords[v][1] for v in I)
    # x ranges over the entire source coordinate set, even when a fiber is empty
    red_counts=[sum(rc[(x+d)%modulus] for d in redD) for x in range(modulus)]
    blue_counts=[sum(bc[(x+d)%modulus] for d in blueD) for x in range(modulus)]
    Lr=sum(comb(a,2) for a in red_counts)
    Lb=sum(comb(a,2) for a in blue_counts)
    return Lr,Lb,red_counts,blue_counts


def max_independent_set(n, edges):
    constraints=lil_matrix((len(edges),n),dtype=float)
    for i,(u,v) in enumerate(sorted(edges)):
        constraints[i,u]=constraints[i,v]=1
    res=milp(c=-np.ones(n),integrality=np.ones(n),bounds=Bounds(np.zeros(n),np.ones(n)),
             constraints=LinearConstraint(constraints.tocsr(),-np.inf,np.ones(len(edges))),
             options={'time_limit':60.0,'mip_rel_gap':1e-10})
    assert res.status==0, res.message
    I={i for i in range(n) if res.x[i]>.5}
    assert len(I)==round(-res.fun)
    return I



def diagonal_quarter_turn_counterexample():
    """Proof-of-concept at finite size; the general lower bound is symbolic."""
    m,u,s,d = 101,10,6,2
    assert (u*u)%m==m-1 and pow(u,4,m)==1
    # The two sources are ordinary cycles generated by +/-1, +/-u.
    U = set(range(10*d))
    K = s*len(U)
    L_R = sum(comb(s*sum((x+t)%m in U for t in (1,-1)),2)
              for x in range(m))
    L_B = sum(comb(s*sum((x+t)%m in U for t in (u,-u)),2)
              for x in range(m))
    fiber_collisions = 2*len(U)*comb(s,2)
    assert L_R + L_B >= d*fiber_collisions
    assert (L_R+L_B)/K**2 > 1/20+5/1000
    # Rotating a -> u a exchanges +/-1 and +/-u.
    assert {u*t%m for t in (1,-1)} == {u,(-u)%m}
    assert {u*t%m for t in (u,(-u)%m)} == {1,m-1}
    print('diagonal counterexample: m,u,s,d,K=',m,u,s,d,K)
    print('L_R, L_B, total=',L_R,L_B,L_R+L_B)
    print('actual ratio=',(L_R+L_B)/(K*K))
    print('same-fiber universal lower ratio=',(s-1)/(10*s))
    print('paper leading threshold=',.05,'epsilon=.001 threshold=',.055)
    print('counterexample PASS')

def main():
    m=13
    shift_set={0,1,5,8,12}
    vertices=[(a,(a+t)%m) for a in range(m) for t in sorted(shift_set)]
    n=len(vertices)
    r=adjacency(vertices,0,{1,12})
    b=adjacency(vertices,1,{5,8})
    E,_,_=mixed_repair(n,r,b)
    I=max_independent_set(n,E)
    assert len(I)==16
    lr,lb,rc,bc=pair_loss(I,vertices)
    # Exact Fourier-equivalent trace identity
    rvec=np.bincount([vertices[v][0] for v in I],minlength=m)
    bvec=np.bincount([vertices[v][1] for v in I],minlength=m)
    Ar=np.array([rvec[(x+1)%m]+rvec[(x-1)%m] for x in range(m)])
    Ab=np.array([bvec[(x+5)%m]+bvec[(x-5)%m] for x in range(m)])
    assert lr+lb == (int(Ar@Ar)+int(Ab@Ab)-4*len(I))//2
    assert (int(Ar@Ar)+int(Ab@Ab)-4*len(I))%2==0
    # Cauchy-Schwarz universal lower bound for arbitrary I:
    # ||Ar||²+||Ab||² >= 2(2K)^2/m
    K=len(I)
    # strict threshold L>=ceil(4K²/13-2K), rounded exactly
    low_num=4*K*K-2*m*K
    lower=(low_num+m-1)//m
    assert lr+lb>=lower
    print(f'n={n}, max independent K={K}; 13-coordinate degree-2 + degree-2 source')
    print('maximum independent set indices:',sorted(I))
    print('pair-loss red,blue,total:',lr,lb,lr+lb)
    print('fraction L/K²:',f'{(lr+lb)/(K*K):.9f}')
    print('universal lower bound L >= 4K²/13-2K:',f'{(4*K*K/13-2*K):.8f}','integer lower',lower)
    print('paper target 1/20*K²:',K*K/20)
    print('source R/B projected occupancies:',sorted(rvec,reverse=True),sorted(bvec,reverse=True))
    print('paper parameters at n65 cannot be used: K_paper=10*sqrt(n log n)>n')
    diagonal_quarter_turn_counterexample()
    print('PASS')

if __name__=='__main__':main()
