"""Scan rooted crossing-free B attachment components for a partial cube not decoded by square transport. Precompute all independent sets of parent, six-set coverage as bit masks. Only inspect components with a potential extra square class and a cycle not generated by squares (GF2 rank screen). Exact intrinsic cuts and square identification decide, not raw-coordinate assumptions. Cap via CLI records."""
import sys,json,itertools
from pathlib import Path
from collections import deque,Counter
import networkx as nx
D=Path(__file__).parent

def audit(B,stats):
    if len(B)<6:return
    adj={s:{s^i for i in [1<<j for j in range(22)] if s^i in B} for s in B};left=B.copy()
    while left:
        root=min(left);V={root};st=[root]
        while st:
            v=st.pop();ns=adj[v]-V;V|=ns;st.extend(ns)
        left-=V;edges=[(u,v) for u in sorted(V) for v in sorted(adj[u]) if u<v];rank=len(edges)-len(V)+1
        if not rank:continue
        idx={e:i for i,e in enumerate(edges)};basis={};par=list(range(len(edges)))
        def rep(i):
            while par[i]!=i:par[i]=par[par[i]];i=par[i]
            return i
        for u,v in edges:
            for w in adj[u]:
                z=w^u^v
                if not (u<v<w<z and z in V):continue
                a,b,c,d=[idx[e] for e in ((u,v),(w,z),(u,w),(v,z))];par[rep(a)]=rep(b);par[rep(c)]=rep(d);x=sum(1<<i for i in (a,b,c,d))
                while x and x.bit_length() in basis:x^=basis[x.bit_length()]
                if x:basis[x.bit_length()]=x
        if len(basis)==rank:continue
        stats['non_square_cycle_components']+=1
        def bfs(s):
            d={s:0};q=deque([s]);
            while q:
                u=q.popleft()
                for v in adj[u]-d.keys():d[v]=d[u]+1;q.append(v)
            return d
        dist={s:bfs(s) for s in V};cuts={};orbit={}
        for i,(u,v) in enumerate(edges):
            c=frozenset(w for w in V if dist[w][u]<dist[w][v]);c=frozenset(V-c) if root in c else c;cuts.setdefault(c,[]).append(i);orbit.setdefault(c,set()).add(rep(i))
        if all(len(x)==1 for x in orbit.values()):continue
        if any(sum((u in c)!=(v in c) for c in cuts)!=dist[u][v] for u,v in itertools.combinations(V,2)):
            stats['nonisometric_split_candidates']+=1;continue
        c=next(c for c in cuts if len(orbit[c])>1);a,b=next((a,b) for a,b in itertools.combinations(cuts[c],2) if rep(a)!=rep(b));return dict(component=sorted(V),component_edges=len(edges),cycle_rank=rank,square_rank=len(basis),square_classes=len({rep(i) for i in range(len(edges))}),metric_axes=len(cuts),separated_edges=[edges[a],edges[b]],graph_edges=edges)

def run(N,k):
    stats=Counter();data=(D/'pauli-realization-catalogues/r37_22.g6').read_bytes().splitlines()[:N]
    for rec,line in enumerate(data,1):
        g=nx.from_graph6_bytes(line);I=[0];
        for v in g:
            h=sum(1<<i for i in g[v]);I.extend([s|1<<v for s in I if not s&h]);
        T=[s for s in I if s.bit_count()==6];hits=[sum(1<<i for i,s in enumerate(T) if s>>v&1) for v in range(22)];allrows=(1<<len(T))-1;cov={0:0}
        for s in I[1:]:b=1<<(s.bit_length()-1);cov[s]=cov[s^b]|hits[s.bit_length()-1]
        for ids in itertools.combinations(range(22),k):
            mask=sum(1<<i for i in ids);must=allrows
            for i in ids:must&=~hits[i]
            B={s for s,val in cov.items() if not s&mask and must&~val==0};stats['cores']+=1;r=audit(B,stats)
            if r:return dict(record=rec,deleted=ids,legal=len(B),stats=stats,**r)
    return dict(stats=stats,examined_parents=N,deletions=k)
if __name__=='__main__':
    r=run(int(sys.argv[1]),int(sys.argv[2]));print({k:v for k,v in r.items() if k not in ('component','graph_edges')});(D/('ramsey_long_circuit_'+sys.argv[2]+'.json')).write_text(json.dumps(r,indent=2)+'\n')
