use serde_json::{json,Value};
use std::{collections::{BTreeMap,BTreeSet},fs};

fn x_vector(label:&str)->Vec<i64>{
    let mut row=vec![0;5];
    for c in label.strip_prefix("g_").unwrap().chars(){row[c.to_digit(10).unwrap() as usize-1]=1;}
    row
}

fn determinant(matrix:&[Vec<i64>])->i64{
    if matrix.len()==1{return matrix[0][0];}
    (0..matrix.len()).map(|column|{
        let minor=(1..matrix.len()).map(|row|(0..matrix.len()).filter(|c|*c!=column).map(|c|matrix[row][c]).collect()).collect::<Vec<Vec<i64>>>();
        (if column%2==0{1}else{-1})*matrix[0][column]*determinant(&minor)
    }).sum()
}

fn combinations(n:usize,k:usize)->Vec<Vec<usize>>{
    fn rec(start:usize,n:usize,k:usize,current:&mut Vec<usize>,out:&mut Vec<Vec<usize>>){
        if current.len()==k{out.push(current.clone());return;}
        for value in start..n{current.push(value);rec(value+1,n,k,current,out);current.pop();}
    }
    let mut out=Vec::new();rec(0,n,k,&mut Vec::new(),&mut out);out
}

fn rank(rows:&[Vec<i64>])->usize{
    let maximum=rows.len().min(5);
    for size in (1..=maximum).rev(){
        for selected_rows in combinations(rows.len(),size){for selected_columns in combinations(5,size){
            let square=selected_rows.iter().map(|r|selected_columns.iter().map(|c|rows[*r][*c]).collect()).collect::<Vec<Vec<i64>>>();
            if determinant(&square)!=0{return size;}
        }}
    }
    0
}

fn pair_key(a:usize,b:usize)->String{format!("F{}-F{}",a.min(b)+1,a.max(b)+1)}

fn rotate_edge_set(edges:&[usize],shift:usize)->BTreeSet<usize>{
    edges.iter().map(|edge|(edge+shift)%5).collect()
}

fn main(){
    let source:Value=serde_json::from_str(&fs::read_to_string("../results/five-site-marked-orbit-norms.json").unwrap()).unwrap();
    let mut pair_labels=BTreeMap::<String,Vec<String>>::new();
    for record in source["two_cut_records"].as_array().unwrap(){
        pair_labels.entry(record["base_collision_factor"].as_str().unwrap().to_owned()).or_default().push(record["label"].as_str().unwrap().to_owned());
    }
    assert_eq!(pair_labels.len(),10);
    assert!(pair_labels.values().all(|labels|labels.len()==2));

    let mut rank_counts=BTreeMap::<usize,usize>::new();
    let mut total_energy_forced=0_usize;
    let mut records=Vec::new();
    let mut occurrence_keys=BTreeSet::new();
    for edges in combinations(5,3){
        let pairs=[pair_key(edges[0],edges[1]),pair_key(edges[0],edges[2]),pair_key(edges[1],edges[2])];
        for choices in 0_usize..8{
            let labels=(0..3).map(|index|pair_labels[&pairs[index]][(choices>>index)&1].clone()).collect::<Vec<_>>();
            let rows=labels.iter().map(|label|x_vector(label)).collect::<Vec<_>>();
            let energy_rank=rank(&rows);
            let mut with_total=rows.clone();with_total.push(vec![1,1,1,1,1]);
            let forces_total=rank(&with_total)==energy_rank;
            *rank_counts.entry(energy_rank).or_default()+=1;
            if forces_total{total_energy_forced+=1;}
            let key=format!("{:?}|{}",edges,choices);assert!(occurrence_keys.insert(key));
            records.push(json!({"edge_triple":edges,"choice_mask":choices,"labels":labels,"energy_rank":energy_rank,"forces_total_energy_zero":forces_total}));
        }
    }
    assert_eq!(records.len(),80);
    for edges in combinations(5,3){
        let orbit=(0..5).map(|shift|rotate_edge_set(&edges,shift)).collect::<BTreeSet<_>>();
        assert_eq!(orbit.len(),5);
    }
    // Three pair-residue lines map to one triple costalk by the oriented row
    // (1,-1,1), whose kernel has rank two: the A2 top OS space.
    let cech_row=[1_i64,-1,1];
    assert!(cech_row.iter().any(|entry|*entry!=0));
    let cech_rank=1_usize;let cech_kernel_rank=3-cech_rank;
    assert_eq!(cech_kernel_rank,2);

    let packet=json!({
        "schema":"marici.benincasa.five_site.triple_collision_cech.v1",
        "edge_triples":10,
        "complementary_occurrence_choices_per_triple":8,
        "labelled_triple_overlaps":records.len(),
        "free_C5_orbits":16,
        "energy_rank_counts":rank_counts,
        "total_energy_forced_count":total_energy_forced,
        "records":records,
        "root_normal_arrangement":"A2: eps_ij=0, eps_jk=0, eps_ik=eps_ij+eps_jk=0",
        "pair_to_triple_cech_row":cech_row,
        "cech_rank":cech_rank,
        "cech_kernel_rank":cech_kernel_rank,
        "top_OS_rank":2,
        "result":"Every labelled triple overlap is generated by the three pair cells with their single oriented A2 relation.",
        "coefficient_excess":false,
        "new_carrier_datum":false
    });
    fs::write("../results/five-site-triple-collision-cech.json",serde_json::to_string_pretty(&packet).unwrap()+"\n").unwrap();
    println!("{}",serde_json::to_string(&packet).unwrap());
}
