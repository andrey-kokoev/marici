use serde_json::{json, Value};
use symbolica::prelude::*;

fn a(s: &str) -> Atom {
    Atom::parse(s, "marici", Default::default()).unwrap()
}
fn clean(x: Atom) -> Atom {
    x.together().cancel().factor()
}
fn shift(v: &[Atom], name: &str) -> Vec<Atom> {
    v.iter()
        .cloned()
        .map(|x| clean(x.replace(a(name).to_pattern()).with((-a(name)).to_pattern())))
        .collect()
}
fn add_signed(vs: &[(&[Atom], i32)]) -> Vec<Atom> {
    (0..vs[0].0.len())
        .map(|i| clean(vs.iter().fold(a("0"), |s, (v, c)| s + a(&c.to_string()) * v[i].clone())))
        .collect()
}
fn equal(x: &[Atom], y: &[Atom]) -> bool {
    x.iter().zip(y).all(|(p, q)| clean(p.clone() - q.clone()) == a("0"))
}

fn main() {
    let prior: Value = serde_json::from_str(
        &std::fs::read_to_string("../string-six-point-circuit-exceptional-cochain.json").unwrap(),
    )
    .unwrap();
    let l: Vec<Atom> = prior["cochain"]
        .as_array()
        .unwrap()
        .iter()
        .map(|x| a(x.as_str().unwrap()))
        .collect();
    let x = shift(&l, "B24");
    let y = shift(&l, "B34");
    let xy = shift(&x, "B34");

    let projections = [
        ("++", add_signed(&[(&l, 1), (&x, 1), (&y, 1), (&xy, 1)])),
        ("-+", add_signed(&[(&l, 1), (&x, -1), (&y, 1), (&xy, -1)])),
        ("+-", add_signed(&[(&l, 1), (&x, 1), (&y, -1), (&xy, -1)])),
        ("--", add_signed(&[(&l, 1), (&x, -1), (&y, -1), (&xy, 1)])),
    ];
    for (label, p) in &projections {
        assert!(p.iter().any(|z| *z != a("0")), "zero projector {label}");
        let ex = if label.starts_with('-') { -1 } else { 1 };
        let ey = if label.ends_with('-') { -1 } else { 1 };
        assert!(equal(&shift(p, "B24"), &p.iter().cloned().map(|z| a(&ex.to_string()) * z).collect::<Vec<_>>()));
        assert!(equal(&shift(p, "B34"), &p.iter().cloned().map(|z| a(&ey.to_string()) * z).collect::<Vec<_>>()));
    }

    let minus_l: Vec<Atom> = l.iter().cloned().map(|z| -z).collect();
    assert!(equal(&shift(&l, "A2"), &minus_l));
    assert!(equal(&shift(&l, "A3"), &minus_l));

    let packet = json!({
        "schema":"marici.benincasa.string_six_point_exceptional_cochain_shift.v1",
        "pivot_shift_characters":{"A2":-1,"A3":-1},
        "pair_shift_group":"(Z/2)^2 generated by B24 and B34 sign changes",
        "nonzero_character_projectors":projections.iter().map(|(label,p)|json!({
            "character":label,
            "nonzero_components":p.iter().filter(|z| **z != a("0")).count()
        })).collect::<Vec<_>>(),
        "character_multiplicities":{"++":1,"-+":1,"+-":1,"--":1},
        "orbit_rank":4,
        "representation":"regular representation of (Z/2)^2",
        "matches_existing_source_shift_character_set":true,
        "classification":"integer pair shifts enlarge the exceptional cochain to the same four-character closure already forced for the source row; no new deck character appears",
        "scope":"finite-difference coefficient representation; not a rational differential connection"
    });
    let text = serde_json::to_string_pretty(&packet).unwrap() + "\n";
    std::fs::write("../string-six-point-exceptional-cochain-shift.json", &text).unwrap();
    print!("{text}");
}
