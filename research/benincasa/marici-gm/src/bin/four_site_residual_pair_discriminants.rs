use serde_json::json;
use std::fs;
use symbolica::prelude::*;

fn atom(text: &str) -> Atom {
    Atom::parse(text, "marici", Default::default()).unwrap().expand()
}

fn clean(x: Atom) -> Atom {
    x.expand().together().cancel().factor()
}

fn quad(a: &[Vec<Atom>], x: &[i32; 3], y: &[i32; 3]) -> Atom {
    let mut out = atom("0");
    for i in 0..3 {
        for j in 0..3 {
            out += atom(&x[i].to_string()) * a[i][j].clone() * atom(&y[j].to_string());
        }
    }
    clean(out)
}

fn main() {
    let g11 = atom("g11"); let g22 = atom("g22"); let g33 = atom("g33");
    let g12 = atom("g12"); let g13 = atom("g13"); let g23 = atom("g23");
    let a11 = clean(g22.clone()*g33.clone()-g23.clone()*g23.clone());
    let a22 = clean(g11.clone()*g33.clone()-g13.clone()*g13.clone());
    let a33 = clean(g11.clone()*g22.clone()-g12.clone()*g12.clone());
    let a12 = clean(g13.clone()*g23.clone()-g12.clone()*g33.clone());
    let a13 = clean(g12.clone()*g23.clone()-g13.clone()*g22.clone());
    let a23 = clean(g12.clone()*g13.clone()-g11.clone()*g23.clone());
    let a = vec![
        vec![a11, a12.clone(), a13.clone()],
        vec![a12, a22, a23.clone()],
        vec![a13, a23, a33],
    ];
    let detg = clean(
        g11.clone()*(g22.clone()*g33.clone()-g23.clone()*g23.clone())
        -g12.clone()*(g12.clone()*g33.clone()-g13.clone()*g23.clone())
        +g13.clone()*(g12.clone()*g23.clone()-g13.clone()*g22.clone())
    );
    let pairs = [
        ("G12_g3", [1,0,-1], [0,0,1], [0,-1,0]),
        ("G12_g34", [1,-1,1], [0,1,-1], [0,1,1]),
    ];
    let mut rows = Vec::new();
    for (name, u, v, n) in pairs {
        let alpha = quad(&a, &u, &u);
        let beta = quad(&a, &u, &v);
        let gamma = quad(&a, &v, &v);
        let determinant = clean(alpha.clone()*gamma.clone()-beta.clone()*beta.clone());
        let normal_gram = clean(quad(
            &vec![vec![g11.clone(),g12.clone(),g13.clone()],
                  vec![g12.clone(),g22.clone(),g23.clone()],
                  vec![g13.clone(),g23.clone(),g33.clone()]], &n, &n));
        assert_eq!(clean(determinant.clone()-detg.clone()*normal_gram.clone()), atom("0"));
        let section = [u[0]+v[0],u[1]+v[1],u[2]+v[2]];
        let section_radicand = quad(&a, &section, &section);
        rows.push(json!({
            "pair": name,
            "u": u, "v": v, "normal": n,
            "alpha": alpha.to_string(),
            "beta": beta.to_string(),
            "gamma": gamma.to_string(),
            "restricted_quadratic_determinant": determinant.to_string(),
            "determinant_factorization": format!("({})*({})",detg,normal_gram),
            "marked_section_radicand": section_radicand.to_string(),
            "binary_quartic_discriminant_support": [
                alpha.to_string(), gamma.to_string(), detg.to_string(), normal_gram.to_string()
            ]
        }));
    }
    let packet = json!({
        "schema":"marici.benincasa.four_site_residual_pair_discriminants.v1",
        "engine":"Symbolica 2.2 exact characteristic-zero factorization",
        "binary_quartic_formula":"disc(alpha*s^4+2*beta*s^2*t^2+gamma*t^4) is a nonzero constant times alpha*gamma*(alpha*gamma-beta^2)^2",
        "representatives":rows,
        "classification":"Every factor is a labelled Gram determinant, Gram quadratic, or marked-point branch collision generated by the frozen relative Cayley-Menger geometry.",
        "new_carrier_datum":false
    });
    let path = "../results/four-site-qg-residual-pair-discriminants.json";
    fs::write(path, serde_json::to_string_pretty(&packet).unwrap()+"\n").unwrap();
    println!("{}", serde_json::to_string(&packet).unwrap());
}
