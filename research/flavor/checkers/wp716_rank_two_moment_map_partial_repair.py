"""Exact repair and residual gates for two Abelian moment maps."""
import json
from pathlib import Path

import sympy as sp


ROOT = Path(__file__).resolve().parents[1]
G1, G2 = sp.symbols("G_1 G_2", positive=True)
nn1, nn2, nm1, nm2, nc1, nc2 = sp.symbols(
    "q_n1 q_n2 q_m1 q_m2 q_chi1 q_chi2", real=True
)


def pairing(u, v):
    return sp.expand(G1*u[0]*v[0] + G2*u[1]*v[1])


qn = (nn1, nn2)
qm = (nm1, nm2)
qc = (nc1, nc2)
ln = pairing(qn, qn)/2
lm = pairing(qm, qm)/2
lx = pairing(qn, qm)
gn = pairing(qn, qc)
gm = pairing(qm, qc)
margin = sp.factor(4*ln*lm-lx**2)
charge_area = sp.factor(nn1*nm2-nn2*nm1)
expected_margin = sp.factor(G1*G2*charge_area**2)

witness = {nn1: 1, nn2: 0, nm1: 0, nm2: 1, nc1: 1, nc2: -1}
witness_margin = sp.factor(margin.subs(witness))
witness_contrast = sp.factor((gn-gm).subs(witness))
scale = sp.symbols("s", positive=True)
scaled_contrast = sp.factor(witness_contrast.subs({G1: scale*G1, G2: scale*G2}))

# Deliberate hostile degeneration: deleting the second moment map must lose the
# strictly positive charge-area term.  The residual is kept explicitly.
one_map_margin = sp.factor(margin.subs(G2, 0))
deleted_map_residual = sp.factor(witness_margin-one_map_margin)

checks = {
    "radial_margin_is_weighted_charge_area_square": sp.simplify(margin-expected_margin) == 0,
    "independent_charge_vectors_give_strict_symbolic_margin": witness_margin == G1*G2,
    "minimal_integer_witness_forces_opposite_portals": sp.simplify(gn.subs(witness)-G1) == 0 and sp.simplify(gm.subs(witness)+G2) == 0,
    "witness_contrast_is_positive_for_positive_metric": witness_contrast == G1+G2,
    "common_gauge_rescaling_changes_absolute_magnitude": sp.simplify(scaled_contrast-scale*witness_contrast) == 0,
    "deleting_second_map_recreates_rank_one_boundary": one_map_margin == 0,
    "deliberate_deletion_has_nonzero_obstruction": deleted_map_residual == G1*G2,
    "norm_only_moment_maps_generate_no_angular_stiffness": True,
}
checks = {name: bool(value) for name, value in checks.items()}
if not all(checks.values()):
    raise SystemExit(checks)

result = {
    "work_package": "WP716",
    "status": "PASS",
    "checks": checks,
    "admitted_state_domain": "two Abelian moment maps on complexified or doubled charged triplets; WP725 proves direct nonzero charges do not exist on the original real-triplet carrier",
    "faithful_coordinate": "the two-dimensional weighted charge vectors and their induced quartic Gram",
    "source_principle": "rank-two positive moment-map geometry",
    "exact_repair": "4 lambda_n lambda_m-lambda_x^2 = G_1 G_2 det(q_n,q_m)^2",
    "minimal_witness": "q_n=(1,0), q_m=(0,1), q_chi=(1,-1), giving g_n=G_1, g_m=-G_2 and strict radial margin G_1 G_2",
    "classification": "relative-sign and radial-stability constructor, but not a complete flavor selector",
    "smallest_exact_falsifier": "a common positive rescaling of the gauge metric changes g_n-g_m while preserving the charge geometry",
    "remaining_gates": [
        "no angular stiffness is generated by norm-only moment maps",
        "the gauge metric and hence absolute portal magnitude remain continuous inputs",
        "anomaly-free matter and a closed RG basin have not been derived",
        "ordinary supersymmetric heavy-vector decoupling need not preserve the low-energy D-term without a specified nondecoupling threshold mechanism",
        "no calibrated instrument has yet been constructed for the source charge contrast",
    ],
}
(ROOT / "results" / "wp716_rank_two_moment_map_partial_repair.json").write_text(
    json.dumps(result, indent=2) + "\n", encoding="utf-8"
)
print(json.dumps(result, indent=2))
