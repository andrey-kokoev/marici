"""Resolve a deferred collective-center -> receiver segment.

The logical segment is declared before source resolution. Its sender is the
normalized collective line, not a primitive face vertex. An explicit sender
port and a checked alias compilation are both counted without conflating them.
"""
from pathlib import Path
from hashlib import sha256
from copy import deepcopy
import json
from fractions import Fraction as Q
from check_geometric_cycle_reversal import geo, SOURCE, verify as verify_proton, ONE, ZERO, conj
from check_reversed_coefficient_attachment import weight, times, div, multiply, encode
from check_retained_barycenter_attachment import rank_columns

BASE=Path(__file__).resolve().parents[1]
DECLARATION={
    'kind':'deferred-collective-center-segment',
    'sender':{'id':'p','resolve':'normalized one-dimensional collective mode generated by the proton protocol',
              'spatial_marker':'barycenter of ABCD'},
    'receiver':{'id':'q','type':'Q(sqrt(-3))','outgoing_generators':[]},
    'logical_arrow':{'source':'p','target':'q','weight':['1','0']},
    'schedule':'complete proton return, resolve p, then traverse p->q',
    'spatial_receiver_position':'not selected by this coefficient construction',
}

def digest(x): return sha256(b'marici.center-segment.v1\0'+json.dumps(x,sort_keys=True,separators=(',',':')).encode()).hexdigest()
def arrow(s,t,z): return {'source':list(s),'target':list(t),'weight_real':str(z[0]),'weight_imag_sqrt3':str(z[1])}
def apply(a,x): return [r[0] for r in multiply(a,[[z] for z in x])]

def resolve(source,declaration):
    if declaration!=DECLARATION: raise ValueError('deferred segment contract changed')
    proof,rows=verify_proton(source)
    objects=source['objects']; geometry=objects[objects[source['root']]['geometry']]['payload']
    points=dict(geo.POINTS)
    for face in ('ABC','ABD','ACD','BCD'): points['F_'+face]=geo.mean([points[k] for k in face])
    c=(ONE,geo.OMEGA,geo.zmul(geo.OMEGA,geo.OMEGA))
    vectors={r['outer_arrow']:geo.zmv(geo.transpose(tuple(points[k] for k in r['triangle'])),c) for r in geometry['triangles_and_transports']}
    labels=sorted({tuple(r['source'][1:]) for r in rows}); idx={p:i for i,p in enumerate(labels)}
    u=[vectors[e]['xyz'.index(axis)] for e,axis in labels]
    norm=sum(geo.znorm(z) for z in u)
    B=[[geo.zscale(conj(z),1/norm) for z in u]]
    U=[[z] for z in u]
    N=[[ZERO]*36 for _ in range(36)]
    for r in rows:
        if r['source'][0]=='aligned': N[idx[tuple(r['target'][1:])]][idx[tuple(r['source'][1:])]]=weight(r)
    if multiply(U,B)!=N or multiply(B,U)!=[[ONE]]: raise ValueError('collective line resolution failed')
    j=next(i for i,z in enumerate(u) if z!=ZERO)
    readout=[ZERO]*36; readout[j]=div(ONE,u[j])
    if multiply([readout],N)!=B: raise ValueError('post-return representative does not resolve center')
    old_port=('raw',)+labels[j]; center=('collective-center','p','amplitude'); receiver=('receiver','q','amplitude')
    explicit=[arrow(old_port,center,readout[j]),arrow(center,receiver,ONE)]
    compact=[arrow(old_port,receiver,readout[j])]
    record={'kind':'resolved-collective-center-segment','proton_root':source['root'],
        'declaration_digest':digest(declaration),'coordinate_order':[list(p) for p in labels],
        'collective_vector':encode(u),'collective_norm_squared':str(norm),'center_functional':encode(B[0]),
        'sender_representation':{'existing_port':list(old_port),'normalization':encode(readout[j]),
            'validity':'on the output of the completed proton return N, not on arbitrary initial raw data',
            'all_nonzero_coordinate_choices_equivalent':True},
        'explicit_center_arrows':explicit,'alias_arrows':compact,
        'primary_protocol':'raw->local->aligned->raw->collective-center/p->receiver/q',
        'outputs':{'proton':'N x','center':'B x','receiver':'B x'},
        'counts':{'retained_proton':len(rows),'explicit_center_total':len(rows)+2,'sender_alias_total':len(rows)+1},
        'spatial_sender':list(map(str,geo.mean([geo.POINTS[k] for k in 'ABCD']))),
        'spatial_receiver':None}
    return record,rows,labels,u,B,U,N,readout

def verify(packet):
    record,*_=resolve(packet['proton'],packet['declaration'])
    if record!=packet['record'] or digest(record)!=packet['root']: raise ValueError('compiled segment mismatch')
    return True

def main():
    original=SOURCE.read_bytes(); source=json.loads(original)
    record,rows,labels,u,B,U,N,r=resolve(source,DECLARATION)
    readout=multiply([r],N)
    representatives=[]
    for j,z in enumerate(u):
        probe=[ZERO]*36; probe[j]=div(ONE,z)
        representatives.append(multiply([probe],N)==B)
    scalars=[ONE,geo.OMEGA,geo.zmul(geo.OMEGA,geo.OMEGA),(Q(2),Q(-1)),ZERO]
    coherent=all(apply(N,[times(z,x) for x in u])==[times(z,x) for x in u]
                 and apply(readout,[times(z,x) for x in u])==[z] for z in scalars)
    # Explicit counterexample to reading the chosen raw coordinate too early.
    j=next(i for i,z in enumerate(r) if z!=ZERO)
    k=next(i for i in range(36) if i!=j and B[0][i]!=ZERO)
    raw_basis=[ONE if i==k else ZERO for i in range(36)]
    premature=apply([r],raw_basis); completed=apply(readout,raw_basis)
    # Check the output functional is invariant under the original tetrahedral
    # rotations. Selecting a representative coordinate marks no physical face.
    objects=source['objects']; geometry=objects[objects[source['root']]['geometry']]['payload']
    invariant=True; index={p:i for i,p in enumerate(labels)}; fixed_point_equations=[]
    for row in geometry['triangles_and_transports']:
        R=tuple(tuple(Q(x) for x in line) for line in row['rotation'])
        fixed_point_equations.extend([[R[i][j]-Q(i==j) for j in range(3)] for i in range(3)])
        rename={a:next(b for b in 'ABCD' if geo.mv(R,geo.POINTS[a])==geo.POINTS[b]) for a in 'ABCD'}
        for column,(edge,axis) in enumerate(labels):
            rotated=[ZERO]*36
            for i in range(3): rotated[index[(''.join(rename[c] for c in edge),'xyz'[i])]]=(R[i]['xyz'.index(axis)],Q(0))
            invariant &= apply(B,rotated)[0]==B[0][column]
    packet={'schema':'marici.collective-center-segment.v1','proton':source,'declaration':DECLARATION,'record':record,'root':digest(record)}
    replay=verify(json.loads(json.dumps(packet)))
    bad=deepcopy(packet);bad['record']['explicit_center_arrows'][0]['weight_real']='1';bad['root']=digest(bad['record'])
    try: verify(bad); rejected=False
    except ValueError: rejected=True
    def explicit_output(arrows):
        extraction=[ZERO]*36; delivery=ZERO
        for a in arrows:
            if a['target'][0]=='collective-center':
                extraction[index[tuple(a['source'][1:])]]=weight(a)
            elif a['source'][0]=='collective-center': delivery=weight(a)
        return [[times(delivery,z) for z in multiply([extraction],N)[0]]]
    extra=record['explicit_center_arrows']
    deleted_outputs=[explicit_output(extra[:i]+extra[i+1:]) for i in range(2)]
    explicit=rows+extra; compact=rows+record['alias_arrows']
    keys=lambda rs:{(tuple(a['source']),tuple(a['target'])) for a in rs}
    checks={
        'collective_factorization_recovers_actual_N':multiply(U,B)==N,
        'normalized_collective_coordinate_is_identity_on_mode':multiply(B,U)==[[ONE]],
        'post_closure_center_decoder_is_exact_on_all_inputs':readout==B,
        'all_36_coordinate_representatives_give_same_center':len(representatives)==36 and all(representatives),
        'nonzero_coherent_proton_and_receiver_agree':coherent,
        'center_readout_respects_all_twelve_proper_rotations':invariant,
        'barycenter_is_unique_rotation_invariant_spatial_marker':rank_columns([{i:row[j] for i,row in enumerate(fixed_point_equations)} for j in range(3)])==3 and record['spatial_sender']==['0','0','0'],
        'premature_raw_tap_rejected_by_counterexample':premature!=completed,
        'explicit_sender_implementation_has_1838_unique_arrows':len(explicit)==len(keys(explicit))==1838,
        'proved_sender_alias_implementation_has_1837_unique_arrows':len(compact)==len(keys(compact))==1837,
        'normalization_and_segment_each_required_for_typed_receiver_output':explicit_output(extra)==B and all(a!=B and apply(a,u)==[ZERO] for a in deleted_outputs),
        'receiver_has_no_outgoing_primitive_transfers':not any(a['source'][0]=='receiver' for a in explicit),
        'original_return_unchanged_by_terminal_extension':explicit[:1836]==rows,
        'serialized_packet_replays':replay,
        'rehashed_wrong_center_normalization_rejected':rejected,
        'source_unchanged':SOURCE.read_bytes()==original,
    }
    result={'verification_passed':all(checks.values()),'checks':checks,'root':packet['root'],
        'counts':record['counts'],'chosen_sender_representation':record['sender_representation'],
        'outcome':'The deferred center segment resolves and transmits the coherent amplitude unchanged. Nonzero source and receiver are compatible; no three-channel phase mismatch occurs.',
        'count_interpretation':'1838 with an explicit center normalization port and one segment arrow; 1837 if that derived center coordinate is compiled as an alias. These are different typed implementations of the same selected output.',
        'scope':'one terminal scalar channel from the generated collective mode; no receiver tetrahedron, spatial segment length, or binding dynamics is generated',
        'premature_tap_counterexample':{'basis_index':k,'before_closure':encode(premature),'after_closure':encode(completed)},
        'source_sha256':sha256(original).hexdigest(),'checker_sha256':sha256(Path(__file__).read_bytes()).hexdigest()}
    (BASE/'results/collective_center_segment_store.json').write_text(json.dumps(packet,indent=2)+'\n',encoding='utf-8')
    (BASE/'results/collective_center_segment.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))
    if not result['verification_passed']: raise SystemExit(1)

if __name__=='__main__': main()
