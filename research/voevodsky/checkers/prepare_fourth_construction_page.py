"""Render a self-contained viewer from the exact fourth-construction records."""
from pathlib import Path
from fractions import Fraction
from hashlib import sha256
from math import sqrt
import json
from check_geometric_cycle_reversal import geo
ROOT=Path(__file__).resolve().parents[3]
BASE=ROOT/'research/voevodsky'
MARKER='<!-- Generated by prepare_fourth_construction_page.py from the exact bridge stores. -->'
def number(c):return sum(float(Fraction(x))*r for x,r in zip(c,(1,sqrt(3),sqrt(74),sqrt(222))))
def znum(z):return list(map(number,z))
def matrix(m,den=1):return [[[x/den for x in znum(z)] for z in row] for row in m]
def main():
    bridge_raw=(BASE/'results/fourth_construction_bridge_store.json').read_bytes();b=json.loads(bridge_raw)
    raw={k:(BASE/'results'/f).read_bytes() for k,f in [('fourth','conditional_fourth_spinor_store.json'),('geometry','four_six_center_cones.json'),('paired_belt','opposite_branch_belt_store.json')]}
    assert all(sha256(v).hexdigest()==b['source_sha256'][k] for k,v in raw.items())
    x,g,n=(json.loads(raw[k]) for k in ('fourth','geometry','paired_belt'))
    L=[[[0,0] for j in range(12)] for i in range(12)]
    for a in x['arrows']:
        if a['stage']=='L':L[a['target']][a['source']]=znum(a['weight'])
    px=[[row[2*i:2*i+2] for row in L[2*i:2*i+2]] for i in range(6)]
    data={'electron_points':{k:list(map(float,v)) for k,v in geo.POINTS.items()},'electron_faces':[list(f) for f in ('ABC','BAD','CDA','DCB')],
          'belt_points':{k:[sqrt(3)*float(Fraction(v[0])),float(Fraction(v[1])),float(Fraction(v[2]))] for k,v in g['belt_scaled_coordinates'].items()},
          'belt_faces':g['belt_faces'],'signs':n['face_signs'],'projectors':px,
          'electron_encoder':matrix(b['electron_encoder_numerator'],sqrt(znum(b['electron_encoder_denominator_squared'])[0])),
          'fourth_encoder':matrix(b['fourth_encoder_numerator'],sqrt(znum(b['fourth_encoder_denominator_squared'])[0])),
          'bridge':matrix(b['bridge_numerator'],sqrt(znum(b['bridge_denominator_squared'])[0])),
          'source_sha256':b['source_sha256'],'bridge_store_sha256':sha256(bridge_raw).hexdigest()}
    template=(ROOT/'papers/witness-generators/fourth-construction.template.html').read_text(encoding='utf-8')
    assert template.count('__CONSTRUCTION_DATA__')==1
    html=template.replace('__CONSTRUCTION_DATA__',json.dumps(data,separators=(',',':'))).replace('<!doctype html>','<!doctype html>\n'+MARKER,1)
    outputs=[ROOT/'papers/witness-generators/fourth-construction.html',ROOT/'website/public/experiments/fourth-construction.html']
    for p in outputs:
        if p.exists() and MARKER not in p.read_text(encoding='utf-8'):raise RuntimeError('Refusing unowned output '+str(p))
        p.parent.mkdir(parents=True,exist_ok=True);p.write_text(html,encoding='utf-8')
    report={'verification_passed':True,'outputs':[str(p.relative_to(ROOT)) for p in outputs],'html_sha256':sha256(html.encode()).hexdigest(),'bridge_store_sha256':data['bridge_store_sha256']}
    (BASE/'results/fourth_construction_page.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8');print(json.dumps(report,indent=2))
if __name__=='__main__':main()
