"""Publish the existing standalone assembly as a site asset, without changing its scene."""
from pathlib import Path
from hashlib import sha256
import json
import sys

if sys.argv[1:] not in ([],['--electron']):raise SystemExit('Usage: prepare_assembly_ledger_asset.py [--electron]')
ELECTRON=bool(sys.argv[1:])
NAME='electron-spinor-construction.html' if ELECTRON else 'proton-neutron-assembly.html'
ROOT=Path(__file__).resolve().parents[3]
SOURCE=ROOT/'papers/witness-generators'/NAME
TARGET=ROOT/'website/public/experiments'/NAME
MARKER='<!-- Generated by research/voevodsky/checkers/prepare_assembly_ledger_asset.py; edit the source assembly instead. -->'

def main():
    source=SOURCE.read_text(encoding='utf-8')
    if TARGET.exists() and MARKER not in TARGET.read_text(encoding='utf-8'):
        raise SystemExit('Refusing to replace an unowned static asset')
    old='href="../../research/'
    assert source.count(old)==(0 if ELECTRON else 2)
    public=source.replace(old,'href="https://github.com/andrey-kokoev/marici/blob/main/research/')
    public=public.replace('<!doctype html>','<!doctype html>\n'+MARKER,1)
    assert public.split('<script type="module">',1)[1]==source.split('<script type="module">',1)[1]
    TARGET.parent.mkdir(parents=True,exist_ok=True)
    TARGET.write_text(public,encoding='utf-8')
    report={'verification_passed':True,'source':str(SOURCE.relative_to(ROOT)),
            'asset':str(TARGET.relative_to(ROOT)),'public_url':'/experiments/'+NAME,
            'scene_module_unchanged':True,'source_links_made_repository_absolute':source.count(old),
            'source_sha256':sha256(SOURCE.read_bytes()).hexdigest(),'asset_sha256':sha256(TARGET.read_bytes()).hexdigest()}
    out=ROOT/'research/voevodsky/results'/('electron_spinor_asset.json' if ELECTRON else 'assembly_ledger_asset.json')
    out.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
