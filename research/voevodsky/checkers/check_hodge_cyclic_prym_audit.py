def require(condition,message):
    if not condition:
        raise ValueError(message)


def load(name):
    return json.loads((ROOT/name).read_text(encoding='utf-8'))


def source_paths():
    data = load(SNAPSHOT)
    return {SNAPSHOT} | {r['path'] for r in data['files']}


def validate_sources():
    data = load(SNAPSHOT)
    require(data['schema'] == 'marici.hodge-cyclic-prym-sources.v1' and
        data['doi'] == '10.4153/CMB-2004-055-x' and
        data['pdf'] == 'research/voevodsky/inputs/hodge-cyclic-prym-v1/koike-2004.pdf', 'Koike source identity')
    base = 'research/voevodsky/inputs/hodge-cyclic-prym-v1/'
    require(data['rendered_pages'] == [2,3] and data['text'] == base+'koike-2004.txt' and
        len(data['files']) == 7 and {r['path'] for r in data['files']} == {base+name for name in
        ('koike-2004.pdf','koike-2004.txt','koike.p2.png','koike.p3.png','crossref.json',
         'discriminant-search.txt','theorem-search.txt')},'Koike source coverage')
    for r in data['files']:
        require(sha256((ROOT/r['path']).read_bytes()).hexdigest() == r['sha256'],'Koike source drift')
    require((ROOT/data['pdf']).read_bytes().startswith(b'%PDF'),'Koike source not a PDF')
    text = ' '.join((ROOT/data['text']).read_text(encoding='utf-8').split())
    for quote in ('This is a principally polarized 6-dimensional Abelian variety.',
                  'the Shimura variety of dimension 9',
                  'Theorem 2.1 There exists a 4-th cyclic',
                  'Corollary 2.1 The Weil classes are generated by algebraic cycles'):
        require(quote in text,'Koike primary quote missing')


@lru_cache(maxsize=1)
def exact_core():
    types = []
    for a in range(7):
        z = cpow((Q(1),Q(1)),a)
        require(norm(z) == 2**a,'two is not represented by the Gaussian norm control')
        d = Q(-2**a)
        require(valuation3(Q(-3)/d) == 1,'Prym/candidate norm-class parity')
        types.append({'elementary_divisors':[1]*(6-a)+[2]*a,
            'Euler_characteristic':2**a,'raw_Hermitian_determinant':int(d),
            'candidate_ratio_v3':1,'realization_of_this_type_claimed':False})
    # PPAV lattice control: order-four permutation of each E^4 block. Primitive
    # anti-involution lattice has Hermitian block [[0,2i],[-2i,0]]. Not a curve.
    z = (Q(0),Q(0))
    h = [[z for _ in range(6)] for _ in range(6)]
    for k in range(0,6,2):
        h[k][k+1],h[k+1][k] = (0,Q(2)),(0,Q(-2))
    require(gdet(h) == (Q(-64),0),'primitive permutation-lattice determinant')
    changes = 0
    for a in range(7):
        for q in (Q(1,3),Q(1),Q(3),Q(2,3),Q(5,2)):
            for z in ((Q(1),Q(0)),(Q(2),Q(1)),(Q(3),Q(0)),(Q(1,3),Q(2,3))):
                candidate = -3*q**6*norm(z)
                require(valuation3(candidate/Q(-2**a))%2 == 1,'repolarization/basis change erased inert-prime obstruction')
                changes += 1
    return {'complex_dimension':6,'balanced_signature':[3,3],
        'primitive_Prym_polarization_kernel_exponent_divides':2,
        'possible_elementary_divisor_type_bounds':types,
        'Prym_raw_discriminant_norm_class':'-1','fixed_candidate_raw_discriminant_norm_class':'-3',
        'Prym_candidate_ratio_odd_v3':True,'repolarization_basis_controls':changes,
        'PPAV_permutation_lattice_determinant':-64,'PPAV_lattice_control_is_a_curve_Jacobian':False,
        'ramified_cyclic_quartic_covers_included_in_exclusion':True,
        'cyclic_quartic_primitive_Prym_presentation_excluded_on_fixed_Qi_isogeny_class':True}


