"""Mixed host/electron loops using generated coefficients and phase bridges.
No twist is inserted. Positive residuals test full phase, not squared phase.
"""
from collections import defaultdict, deque
from pathlib import Path
from hashlib import sha256
import json
from check_geometric_cycle_reversal import geo, SOURCE, verify, ONE, conj, encode
from check_reversed_coefficient_attachment import weight, times, div

BASE=Path(__file__).resolve().parents[1]

def cycle_products(edges,root):
    adj=defaultdict(list)
    for k,(s,t,h) in enumerate(edges):
        adj[s].append((t,h,k)); adj[t].append((s,div(ONE,h),k))
    q={root:ONE}; tree=set(); queue=deque([root])
    while queue:
        s=queue.popleft()
        for t,h,k in adj[s]:
            if t not in q:
                q[t]=times(h,q[s]); tree.add(k); queue.append(t)
    return q,tree,[(k,div(times(h,q[s]),q[t])) for k,(s,t,h) in enumerate(edges) if k not in tree]

def main():
    original=SOURCE.read_bytes(); source=json.loads(original); evidence,rows=verify(source)
    objects=source['objects']; geometry=objects[objects[source['root']]['geometry']]['payload']
    points=dict(geo.POINTS)
    for face in ('ABC','ABD','ACD','BCD'):
        points['F_'+face]=geo.mean([points[v] for v in face])
    c=(ONE,geo.OMEGA,geo.zmul(geo.OMEGA,geo.OMEGA))
    modes={r['outer_arrow']:geo.zmv(geo.transpose(tuple(points[v] for v in r['triangle'])),c)
           for r in geometry['triangles_and_transports']}
    ports=sorted({tuple(p) for r in rows for p in (r['source'],r['target'])})
    basis={}
    for p in ports:
        v=modes[p[1]]['xyz'.index(p[2])]
        basis[('H',)+p]=v; basis[('E',)+p]=conj(v)
    edges=[]
    for r in rows:
        s,t=tuple(r['source']),tuple(r['target']); h=weight(r)
        edges.extend([(('H',)+s,('H',)+t,h),(('E',)+s,('E',)+t,conj(h))])
    # Selected AB attachment has three raw coefficient channels. No extra
    # intermediate carrier is introduced. Return bridges are inverses.
    bridges=[]
    for axis in 'xyz':
        p=('raw','AB',axis); host=('H',)+p; electron=('E',)+p
        d=div(basis[host],basis[electron])
        bridges.extend([(electron,host,d),(host,electron,div(ONE,d))])
    edges.extend(bridges)
    stripped=[div(times(h,basis[s]),basis[t]) for s,t,h in edges]
    positive=lambda z:z[1]==0 and z[0]>0
    q,tree,cycles=cycle_products(edges,('H','raw','AB','x'))
    # A minus sign is invisible to h/conjugate(h), but must be caught here.
    broken=list(edges); s,t,h=broken[-1]; broken[-1]=(s,t,(-h[0],-h[1]))
    _,_,bad_cycles=cycle_products(broken,('H','raw','AB','x'))
    checks={
        'source_verified':evidence['verified'],
        'both_full_protocols_retained':len(edges)-len(bridges)==3672,
        'three_bidirectional_attachment_channels':len(bridges)==6,
        'joined_graph_connected':len(q)==len(basis)==216,
        'every_generated_edge_has_positive_real_residual':all(map(positive,stripped)),
        'attachment_residuals_are_exactly_one':stripped[-6:]==[ONE]*6,
        'all_3463_fundamental_cycles_have_trivial_full_phase':len(cycles)==3463 and all(positive(z) for _,z in cycles),
        'minus_sign_negative_control_detected':any(not positive(z) for _,z in bad_cycles),
        'minus_sign_is_invisible_to_squared_phase':div(broken[-1][2],conj(broken[-1][2]))==div(edges[-1][2],conj(edges[-1][2])),
        'source_unchanged':SOURCE.read_bytes()==original,
    }
    result={
        'verification_passed':all(checks.values()),'checks':checks,
        'contract':{'host':'original L/G/N protocol','electron':'conjugated coefficients derived from reversed local cycles',
                    'attachment':'raw AB x/y/z channels; D=diag(v/conjugate(v)), with inverse return',
                    'phase_test':'full complex phase; cycle magnitudes may differ from one'},
        'vertices':len(basis),'arrows':len(edges),'tree_edges':len(tree),'fundamental_cycles':len(cycles),
        'attachment_bridges':[{'source':list(s),'target':list(t),'weight':encode(h)} for s,t,h in bridges],
        'general_argument':'Every coefficient has h = a * b_target/b_source with a positive real. '
             'Therefore every closed product is positive real, including loops crossing the attachment. '
             'This holds for any subset of matching-port bridges generated by the same b ratio.',
        'outcome':'The generated attachment has no nontrivial phase holonomy. It supplies no second holonomy closure.',
        'source_root':source['root'],'source_sha256':sha256(original).hexdigest(),
        'checker_sha256':sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (BASE/'results/generated_attachment_holonomy.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))
    if not result['verification_passed']: raise SystemExit(1)

if __name__=='__main__': main()
