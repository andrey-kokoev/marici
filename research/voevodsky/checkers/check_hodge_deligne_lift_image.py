def rank(rows):
    a=[[Q(x) for x in r] for r in rows];k=0
    for j in range(len(a[0])):
        pivot=next((i for i in range(k,len(a)) if a[i][j]),None)
        if pivot is None:continue
        a[k],a[pivot]=a[pivot],a[k]
        d=a[k][j];a[k]=[x/d for x in a[k]]
        for i in range(len(a)):
            if i!=k:
                d=a[i][j];a[i]=[x-d*y for x,y in zip(a[i],a[k])]
        k+=1
    return k


def differential(v):
    a1,a2,f,h1,h2=v
    return (a1-f,-f-h2,a2)


def main():
    matrix=[[1,0,-1,0,0],[0,0,-1,0,-1],[0,1,0,0,0]]
    assert rank(matrix)==3 and 5-rank(matrix)==2
    # Entire kernel parametrized by (t,0,t,s,-t); projection to A is (t,0).
    for t,s in product((Q(-2),Q(0),Q(1,2),Q(1)),repeat=2):
        assert differential((t,0,t,s,-t))==(0,0,0)
    assert differential((1,0,1,0,0))!=(0,0,0)  # retaining homotopy is essential
    assert differential((1,0,1,0,1))!=(0,0,0)  # incorrect cone sign
    assert differential((0,1,0,0,0))[2]==1  # no f or h can remove this component
    kernel_basis=[[1,0,1,0,-1],[0,0,0,1,0]]
    assert rank(kernel_basis)==2
    assert rank([[1,0],[0,0]])==1  # rank of projection on this kernel
    # H5(C)=Q generated by h1, since dC has rank one and no incoming boundary.
    assert 2-rank([[0,1]])==1
    b5=sum(comb(6,r)*comb(6,5-r) for r in range(6))
    f3=sum(comb(6,r)*comb(6,5-r) for r in range(3,6))
    assert (b5,f3,b5-f3)==(792,396,396)
    result={'passed':True,'classification':'Deligne_lift_exists_not_algebraic_image_membership',
        'finite_cone_kernel_dimension':2,'finite_projection_image_dimension':1,
        'finite_lift_ambiguity_dimension':1,'sixfold_b5':b5,'sixfold_F3_H5_dimension':f3,
        'actual_periods_computed':False,'algebraic_regulator_image_computed':False,
        'Hodge_proved':False,'Hodge_refuted':False,
        'next_test':'Algebraic support localization in degree six and purity.'}
    root=Path(__file__).resolve().parents[3]
    (root/'research/voevodsky/results/hodge-deligne-lift-image-v1.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result))


